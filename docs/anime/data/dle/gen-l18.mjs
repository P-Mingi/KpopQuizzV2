#!/usr/bin/env node
// Lane magazine, round 2 (run O1, owner 2026-11-08): writes launch/L18-l1-otakudle-genres.sql and its rollback.
//
//   node docs/anime/data/dle/gen-l18.mjs [--check]
//
// Reads  docs/anime/data/dle/otakudle-genres.json (50 series: the genres of the infobox mapped to the closed list, the Wikipedia page and revision; written by gen-genres.mjs),
//        docs/anime/data/dle/otakudle-magazine.json (sourced research, not displayed: only its 5 work years are read here),
//        docs/anime/data/dle/otakudle-species-fixes.json (16 species values),
//        docs/pending-migrations/multisite/023-dle-otakudle.sql (the view it replaces, and restores in the rollback).
// Same input, same bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MIG = path.resolve(HERE, '../../../pending-migrations/multisite');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const data = JSON.parse(readFileSync(path.join(HERE, 'otakudle-genres.json'), 'utf8'));
const mag = JSON.parse(readFileSync(path.join(HERE, 'otakudle-magazine.json'), 'utf8'));
const { LIST } = await import('./gen-genres.mjs');
const fixes = JSON.parse(readFileSync(path.join(HERE, 'otakudle-species-fixes.json'), 'utf8'));
const v023 = readFileSync(path.join(MIG, '023-dle-otakudle.sql'), 'utf8');

const start = v023.indexOf('create or replace view public.dle_src_anime_character');
const end = v023.indexOf('from pool p;', start) + 'from pool p;'.length;
const oldView = v023.slice(start, end);
const swap = (s, from, to) => { if (!s.includes(from)) throw new Error(`023 changed: ${from}`); return s.replace(from, to); };
let newView = oldView;
newView = swap(newView, 'g.slug as series_slug, s.title_en, s.aliases as series_aliases, sf.demographic,', 'g.slug as series_slug, s.title_en, s.aliases as series_aliases, sf.genres,');
newView = swap(newView, "case when s.type = 'anime_original' then s.anime_start_year else s.manga_start_year end as work_year,", "coalesce(sf.work_year, case when s.type = 'anime_original' then s.anime_start_year else s.manga_start_year end) as work_year,");
newView = swap(newView, "'demographic', jsonb_build_object('v', p.demographic),", "'genres', jsonb_build_object('v', to_jsonb(p.genres)),");

const WSJ_FIX = ['demon-slayer', 'jujutsu-kaisen', 'naruto'];
const years = mag.filter((d) => d.work_year !== undefined);
const KEYS = LIST.map((l) => l[0]);
const maxShared = Math.max(...Object.values(data.reduce((m, d) => { const k = d.genres.join(','); m[k] = (m[k] ?? 0) + 1; return m; }, {})));

const pairs = (xs) => xs.map((x) => `    (${q(x.series)}, ${q(x.character)}, ${q(x.from)}, ${q(x.to)})`).join(',\n');
const pairsBack = (xs) => xs.map((x) => `    (${q(x.series)}, ${q(x.character)}, ${q(x.to)}, ${q(x.from)})`).join(',\n');

const yearOf = (slug) => years.find((y) => y.series === slug)?.work_year;
const rowsGenres = data.map((d, i) => {
  const y = yearOf(d.series);
  return `    (${q(d.series)}, array[${d.genres.map(q).join(', ')}]::text[], ${y === undefined ? 'null::int' : y})${i === data.length - 1 ? '' : ','}`;
}).join('\n');

const permalink = (d) => `https://en.wikipedia.org/w/index.php?title=${encodeURIComponent(d.wikipedia_title.replace(/ /g, '_'))}&oldid=${d.revid}`;
const genreSrc = data.map((d) => `    (${q(d.series)}, 'otakudle.genres', ${q(d.revid)}, ${q(permalink(d))})`).join(',\n');
const yearSrc = years.map((d) => `    (${q(d.series)}, 'otakudle.year', ${q(d.revision)}, ${q(d.source)})`).join(',\n');

const sql = `-- L18-l1-otakudle-genres.sql (lane magazine, round 2, run O1, owner 2026-11-08; generated by docs/anime/data/dle/gen-l18.mjs, do not edit by hand)
--
-- What:   Otakudle (the anime mix), column Demographic replaced by Genres: the genres of the work, 1 to 3 words of a closed list of ${LIST.length}, taken from the Genre line of the English Wikipedia infobox
--         of the original work of each of the 50 series and mapped by a fixed rule (docs/anime/data/dle/otakudle-genres-map.md; the page and the revision read are in otakudle-genres.json and in
--         entity_sources, field otakudle.genres). Kind multi: dle_compare (019) is unchanged and already does the job: the same set is Right, one genre in common is Near, none is Wrong.
--         The closed list: ${LIST.map((l) => l[0]).join(', ')}. No exact set of genres is shared by more than ${maxShared} series (the largest set), the objective being 5.
--         The column order becomes Series, Genres, Year, Studio, Gender, Species, Role (seven compared columns, the check of 023 still holds); the year header "Debut year" is renamed in the app
--         ("Series year"), the value is unchanged in kind. The magazine and the publisher of each series are NOT in this file: they stay as sourced research in docs/anime/data/dle/otakudle-magazine.json, not displayed.
--         1. series_facts gets two columns: genres (text[], 1 to 3 words, every word in the closed list) and work_year. series_facts.demographic stays, unread.
--         2. The view dle_src_anime_character is replaced (attrs.genres instead of attrs.demographic; the year reads series_facts.work_year first, then the manga or anime start year as in 023).
--            work_year is set for the four series that had no start year: Re:Zero 2012, Sword Art Online 2002, Mob Psycho 100 2012, Steins;Gate 2009 (their seven featured characters can now be the answer),
--            and for One-Punch Man: 2009 (owner's answer, 2026-11-08), the year of ONE's self-published webcomic, the first web publication, as Re:Zero and Sword Art Online take the first web publication.
--            Both sources of One-Punch Man are on the English Wikipedia page One-Punch_Man (revision 1384356976): the infobox lists ONE's webcomic (2009) and the Tonari no Young Jump remake (2012).
--         3. dle_attributes of the game otakudle: demographic removed, genres added, positions 1 to 7 = series, genres, year, studio, gender, species, role.
--         4. The spelling "Weekly Shonen Jump" (Demon Slayer, Jujutsu Kaisen, Naruto, L04) is "Weekly Shōnen Jump" everywhere, as in the other series.
--         5. Species written wrong (the slug lost a long vowel or a final s, or turned a possessive into "-s-"): ${fixes.length} values, listed in docs/anime/data/dle/otakudle-species-fixes.json (homunculus, dog-daiyokai,
--            red-witches, silver-dwarves, bibidi-race ...). Natsu Dragneel was demon (E.N.D., a late reveal): he is human, as first met. updated_at is not touched, so the rollback is exact.
--         6. The snapshot the players read (dle_entities) is refreshed when the game already has one.
--         Nothing else: no other game, no kpop row.
-- Needs:  019, 023, L04, L13 (series_facts rows and character_facts), L17 (this file applies after it, after #215).
-- WHEN:   apply by the owner after a backup, at a day boundary: after 00:30 UTC and never between 23:50 and 00:30 UTC, and never during a build. A guess is stored as the entity id only (dle_plays.guesses) and its
--         colours are computed on every read (dle_play_state -> dle_compare_all) from the live columns of dle_attributes and the dle_entities snapshot: a game already played today is recoloured at once
--         (the Demographic cell of a past guess becomes its Genres cell), and this file refreshes the snapshot in the same transaction, so the grid never mixes old and new values. A player with the page open
--         keeps the old column header until the page is reloaded. Today's answer does not change (the day is in dle_schedule); the seven characters of the four series that had no year become eligible for the bank,
--         which the nightly maintenance rebuilds when the pool hash changes (it keeps today and the 7 days after it).
--         023 builds the old view: do not run 023 again after this file (session.sh runs it before L13, which is before this file).
--         L13 still carries the 16 old species (its source, scripts/anime/a2/data/all-series.json, belongs to another lane: see docs/o1/requests/L1.md): run L13 never again after this file, or run this file again.
-- Undo:   L18-l1-otakudle-genres.rollback.sql (the view of 023, the seven old columns, the old species, the old spelling, the columns dropped).
-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing.

set lock_timeout = '5s';
set client_min_messages = warning;

do $l18$ begin
  if to_regclass('public.series_facts') is null or to_regclass('public.character_facts') is null or to_regclass('public.dle_attributes') is null then
    raise exception 'L18: 019 and 023 must be applied first';
  end if;
  if (select count(*) from public.series_facts) < 50 then
    raise exception 'L18: the 50 series_facts rows of L13 are not all there (apply L13 first)';
  end if;
  if to_regclass('public.character_game_facts') is null or not exists (select 1 from public.dle_attributes where game_id = 'otakudle-one-piece' and key = 'affiliation' and kind = 'single') then
    raise exception 'L18: L17 must be applied first';
  end if;
end $l18$;

alter table public.series_facts add column if not exists genres text[] check (genres is null or (cardinality(genres) between 1 and 3 and genres <@ array[${KEYS.map(q).join(', ')}]::text[]));
alter table public.series_facts add column if not exists work_year smallint check (work_year is null or work_year between 1900 and 2100);

-- 1. The genres and the work year of the 50 series. A null work_year means: keep the start year of the series row.
with n(slug, genres, work_year) as (values
${rowsGenres}
)
update public.series_facts sf
set genres = n.genres, work_year = n.work_year::smallint
from n
join public.groups g on g.site_id = 'anime' and g.slug = n.slug
where sf.group_id = g.id and (sf.genres, sf.work_year) is distinct from (n.genres, n.work_year::smallint);

with s(slug, field, rev, url) as (values
${genreSrc},
${yearSrc}
)
insert into public.entity_sources (entity_type, entity_id, field, source, source_ref, source_url, fetched_at)
select 'series', s.slug, s.field, 'wikipedia', s.rev, s.url, '2026-11-08T00:00:00Z'::timestamptz from s
on conflict (entity_type, entity_id, field, source) do nothing;

-- 4. One spelling of Weekly Shōnen Jump.
update public.series s set magazine = 'Weekly Shōnen Jump'
from public.groups g
where g.id = s.group_id and g.site_id = 'anime' and g.slug in (${WSJ_FIX.map(q).join(', ')}) and s.magazine = 'Weekly Shonen Jump';

-- 5. Species.
with f(series, character, old_value, new_value) as (values
${pairs(fixes)}
)
update public.character_facts cf set species = f.new_value
from f
join public.groups g on g.site_id = 'anime' and g.slug = f.series
join public.characters c on c.group_id = g.id and c.slug = f.character
where cf.character_id = c.id and cf.species = f.old_value;

-- Natsu Dragneel: the Wikipedia row of his old value (Demon (Etherious)) does not support human.
delete from public.entity_sources where entity_type = 'character' and entity_id = 'natsu-dragneel' and field = 'species' and source = 'wikipedia';

-- 2. The view of the game.
${newView}

revoke all on table public.dle_src_anime_character from public, anon, authenticated;
grant select on table public.dle_src_anime_character to service_role;

-- 3. The columns of the game: series, genres, year, studio, gender, species, role. Two steps because (game_id, position) is unique.
do $l18$ begin
  if exists (select 1 from public.dle_games where id = 'otakudle') and not exists (select 1 from public.dle_attributes where game_id = 'otakudle' and key = 'genres') then
    delete from public.dle_attributes where game_id = 'otakudle' and key = 'demographic';
    update public.dle_attributes set position = case key when 'gender' then 8 when 'species' then 9 when 'role' then 10 when 'year' then 11 when 'studio' then 12 end
      where game_id = 'otakudle' and key in ('gender', 'species', 'role', 'year', 'studio');
    insert into public.dle_attributes (game_id, key, kind, position, near) values ('otakudle', 'genres', 'multi', 2, null);
    update public.dle_attributes set position = case key when 'year' then 3 when 'studio' then 4 when 'gender' then 5 when 'species' then 6 when 'role' then 7 end
      where game_id = 'otakudle' and key in ('gender', 'species', 'role', 'year', 'studio');
  end if;
end $l18$;

-- 6. The snapshot the players read.
do $l18$ begin
  if exists (select 1 from public.dle_entities where game_id = 'otakudle') then
    perform public.dle_refresh_entities('otakudle');
  end if;
end $l18$;

-- Self-check.
do $l18$ begin
  if exists (select 1 from public.series_facts sf join public.groups g on g.id = sf.group_id and g.site_id = 'anime' where sf.genres is null) then
    raise exception 'L18: a series has no genres';
  end if;
  if (select max(c) from (select count(*) as c from public.series_facts where genres is not null group by genres) x) > 5 then
    raise exception 'L18: an exact set of genres is shared by more than 5 series';
  end if;
  if exists (select 1 from public.dle_games where id = 'otakudle') and
     (select string_agg(key, ',' order by position) from public.dle_attributes where game_id = 'otakudle') <> 'series,genres,year,studio,gender,species,role' then
    raise exception 'L18: otakudle does not have its 7 columns in order';
  end if;
  if pg_get_viewdef('public.dle_src_anime_character'::regclass) !~ 'genres' or pg_get_viewdef('public.dle_src_anime_character'::regclass) !~ 'published' then
    raise exception 'L18: the view lost the genres or its published rule';
  end if;
  if has_table_privilege('anon', 'public.dle_src_anime_character', 'select') or has_table_privilege('authenticated', 'public.dle_src_anime_character', 'select') then
    raise exception 'L18: dle_src_anime_character is readable by a browser role';
  end if;
end $l18$;

notify pgrst, 'reload schema';
`;

const rollback = `-- L18-l1-otakudle-genres.rollback.sql (lane magazine, round 2, run O1; generated by docs/anime/data/dle/gen-l18.mjs, do not edit by hand)
--
-- What:   undoes L18: the view of 023 (Demographic) back, the seven old columns of the game otakudle in their old order (series, gender, species, role, demographic, year, studio), the old species values
--         (and the Wikipedia row of Natsu Dragneel), the old spelling "Weekly Shonen Jump" of Demon Slayer, Jujutsu Kaisen and Naruto, the entity_sources rows of L18, then the two columns of series_facts dropped.
--         series_facts.demographic was never touched. Apply at a day boundary like L18 (same remark on guesses). Idempotent.
-- o1-transaction: single (psql --single-transaction).

set lock_timeout = '5s';
set client_min_messages = warning;

-- The view first: the columns it reads are dropped last.
${oldView}

revoke all on table public.dle_src_anime_character from public, anon, authenticated;
grant select on table public.dle_src_anime_character to service_role;

do $l18$ begin
  if exists (select 1 from public.dle_games where id = 'otakudle') and exists (select 1 from public.dle_attributes where game_id = 'otakudle' and key = 'genres') then
    delete from public.dle_attributes where game_id = 'otakudle' and key = 'genres';
    update public.dle_attributes set position = case key when 'gender' then 8 when 'species' then 9 when 'role' then 10 when 'year' then 11 when 'studio' then 12 end
      where game_id = 'otakudle' and key in ('gender', 'species', 'role', 'year', 'studio');
    insert into public.dle_attributes (game_id, key, kind, position, near) values ('otakudle', 'demographic', 'single', 5, null);
    update public.dle_attributes set position = case key when 'gender' then 2 when 'species' then 3 when 'role' then 4 when 'year' then 6 when 'studio' then 7 end
      where game_id = 'otakudle' and key in ('gender', 'species', 'role', 'year', 'studio');
  end if;
end $l18$;

with f(series, character, old_value, new_value) as (values
${pairsBack(fixes)}
)
update public.character_facts cf set species = f.new_value
from f
join public.groups g on g.site_id = 'anime' and g.slug = f.series
join public.characters c on c.group_id = g.id and c.slug = f.character
where cf.character_id = c.id and cf.species = f.old_value;

insert into public.entity_sources (entity_type, entity_id, field, source, source_ref, source_url, fetched_at)
select 'character', 'natsu-dragneel', 'species', 'wikipedia', null, 'https://en.wikipedia.org/wiki/Natsu_Dragneel', '2026-11-02T00:00:00Z'::timestamptz
where exists (select 1 from public.characters c join public.groups g on g.id = c.group_id where g.site_id = 'anime' and g.slug = 'fairy-tail' and c.slug = 'natsu-dragneel')
on conflict (entity_type, entity_id, field, source) do nothing;

update public.series s set magazine = 'Weekly Shonen Jump'
from public.groups g
where g.id = s.group_id and g.site_id = 'anime' and g.slug in (${WSJ_FIX.map(q).join(', ')}) and s.magazine = 'Weekly Shōnen Jump';

delete from public.entity_sources where entity_type = 'series' and field in ('otakudle.genres', 'otakudle.year');

alter table public.series_facts drop column if exists genres, drop column if exists work_year;

do $l18$ begin
  if exists (select 1 from public.dle_entities where game_id = 'otakudle') then
    perform public.dle_refresh_entities('otakudle');
  end if;
end $l18$;

notify pgrst, 'reload schema';
`;

if (process.argv.includes('--check')) {
  const dir = path.join(MIG, 'launch');
  const same = readFileSync(path.join(dir, 'L18-l1-otakudle-genres.sql'), 'utf8') === sql && readFileSync(path.join(dir, 'L18-l1-otakudle-genres.rollback.sql'), 'utf8') === rollback;
  console.log(same ? 'same' : 'DIFFERENT');
  process.exit(same ? 0 : 1);
}
writeFileSync(path.join(MIG, 'launch', 'L18-l1-otakudle-genres.sql'), sql);
writeFileSync(path.join(MIG, 'launch', 'L18-l1-otakudle-genres.rollback.sql'), rollback);
console.log(`written: ${data.length} series, ${years.length} years, ${fixes.length} species, largest shared set ${maxShared}`);
