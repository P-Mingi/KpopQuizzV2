-- 001-schema.sql (Bunnyverse Cards, lane CORE, 2026-11-12; the tables of the card game)
--
-- What:   creates the 8 tables of the contract (docs/o1/briefs/CARDS-CONTRACT.md section 2): cards_entities, cards_photos, cards_catalog,
--         cards_wallets, cards_owned, cards_packs, cards_ad_tickets, cards_reports, with their keys, checks and indexes. Empty. 002 adds the
--         functions, 003 the RLS, the grants and the storage bucket.
-- Why:    docs/design/cards/CARDS-PLAN-v3.md: a stack of 5 packs, a refill every 10 minutes, 5 cards a pack, shards, a rewarded ad per pack,
--         a binder per account, and a credit and licence for every photo. Every value a player sees is read from these tables.
-- Rows:   0 rows. 8 tables, 11 indexes besides the keys. Additive: no existing table is touched. No XP, level, streak or badge is read or written.
-- Needs:  auth.users (always there). The catalog is filled by the 1xx files of the DATA lane, after this file.
-- Notes:  the wallet row of a player is created by his first pack (cards_apply_pack); until then cards_wallet reads a virtual full stack.
--         User tables cascade on auth.users, so the account deletion removes the collection, the packs and the tickets with the account.
-- Verify: select count(*) from information_schema.tables where table_schema = 'public' and table_name like 'cards\_%';   expect 8
-- Verify: select count(*) from pg_indexes where schemaname = 'public' and tablename like 'cards\_%';   expect 21
-- Verify: select count(*) from public.cards_catalog;   expect 0
-- Undo:   001-schema.rollback.sql (refused while a player owns a card or opened a pack).
-- o1-transaction: single, ONE DO block (atomic on its own, in psql and in the Supabase SQL Editor). Idempotent: a second run changes nothing.

do $c001$
begin
  perform set_config('lock_timeout', '5s', true);
  perform set_config('client_min_messages', 'warning', true);

  if to_regclass('auth.users') is null then
    raise exception '001-schema: auth.users is missing';
  end if;

  create table if not exists public.cards_entities (
    id text constraint cards_entities_pkey primary key,
    kind text not null constraint cards_entities_kind_check check (kind in ('idol', 'group', 'event')),
    name text not null constraint cards_entities_name_check check (length(btrim(name)) > 0),
    group_id text constraint cards_entities_group_id_fkey references public.cards_entities(id) on delete set null,
    debut_year integer constraint cards_entities_debut_year_check check (debut_year is null or debut_year between 1900 and 2100),
    qid text,
    sort_key text not null,
    lock_reasons jsonb not null default '{}'::jsonb constraint cards_entities_lock_reasons_check check (jsonb_typeof(lock_reasons) = 'object'),
    active boolean not null default true,
    constraint cards_entities_id_check check (
      (kind = 'idol' and id like 'idol:%') or (kind = 'group' and id like 'group:%') or (kind = 'event' and id like 'event:%'))
  );
  create index if not exists cards_entities_group_idx on public.cards_entities (group_id) where group_id is not null;
  create index if not exists cards_entities_sort_idx on public.cards_entities (sort_key);

  create table if not exists public.cards_photos (
    id bigint generated by default as identity constraint cards_photos_pkey primary key,
    entity_id text not null constraint cards_photos_entity_id_fkey references public.cards_entities(id) on delete cascade,
    slot integer not null constraint cards_photos_slot_check check (slot between 1 and 3),
    source text not null constraint cards_photos_source_check check (source in ('commons', 'koreanet', 'flickr', 'dvids')),
    source_page text not null,
    file_url text not null,
    author text not null constraint cards_photos_author_check check (length(btrim(author)) > 0),
    author_url text,
    licence text not null,
    licence_url text not null,
    share_alike boolean not null,
    checked_at date not null,
    event_name text,
    event_date date,
    focal_x integer not null default 50 constraint cards_photos_focal_x_check check (focal_x between 0 and 100),
    focal_y integer not null default 50 constraint cards_photos_focal_y_check check (focal_y between 0 and 100),
    storage_path text,
    status text not null default 'pending' constraint cards_photos_status_check check (status in ('auto', 'pending', 'approved', 'rejected', 'removed')),
    review_note text,
    modified text not null default 'cropped, frame and text added'
  );
  create index if not exists cards_photos_entity_idx on public.cards_photos (entity_id, slot);
  create index if not exists cards_photos_status_idx on public.cards_photos (status);
  -- One live photo (script-approved or owner-approved) per idol slot; candidates and refused photos can be many.
  create unique index if not exists cards_photos_live_slot_key on public.cards_photos (entity_id, slot) where status in ('auto', 'approved');

  create table if not exists public.cards_catalog (
    card_no integer constraint cards_catalog_pkey primary key constraint cards_catalog_card_no_check check (card_no > 0),
    num text not null constraint cards_catalog_num_key unique constraint cards_catalog_num_check check (num ~ '^BV1-[0-9]{4,}$'),
    entity_id text not null constraint cards_catalog_entity_id_fkey references public.cards_entities(id) on delete cascade,
    rarity text not null constraint cards_catalog_rarity_check check (rarity in ('C', 'U', 'R', 'SR', 'UR', 'L')),
    edition text not null constraint cards_catalog_edition_check check (edition in ('std', 'stage', 'holo', 'era', 'gold', 'full')),
    photo_id bigint constraint cards_catalog_photo_id_fkey references public.cards_photos(id) on delete set null,
    in_packs boolean not null default true,
    constraint cards_catalog_edition_rarity_check check (
      (rarity = 'C' and edition = 'std') or (rarity = 'U' and edition = 'stage') or (rarity = 'R' and edition = 'holo')
      or (rarity = 'SR' and edition = 'era') or (rarity = 'UR' and edition = 'gold') or (rarity = 'L' and edition = 'full')),
    constraint cards_catalog_entity_rarity_key unique (entity_id, rarity)
  );
  create index if not exists cards_catalog_packs_idx on public.cards_catalog (rarity) where in_packs;
  create index if not exists cards_catalog_photo_idx on public.cards_catalog (photo_id) where photo_id is not null;

  create table if not exists public.cards_wallets (
    user_id uuid constraint cards_wallets_pkey primary key constraint cards_wallets_user_id_fkey references auth.users(id) on delete cascade,
    stock integer not null constraint cards_wallets_stock_check check (stock between 0 and 5),
    anchor timestamptz not null,
    paris_day date not null,
    ads_today integer not null default 0 constraint cards_wallets_ads_today_check check (ads_today >= 0),
    bonus_today integer not null default 0 constraint cards_wallets_bonus_today_check check (bonus_today >= 0),
    shards integer not null default 0 constraint cards_wallets_shards_check check (shards >= 0),
    version integer not null default 0,
    updated_at timestamptz not null default now()
  );

  create table if not exists public.cards_owned (
    user_id uuid not null constraint cards_owned_user_id_fkey references auth.users(id) on delete cascade,
    card_no integer not null constraint cards_owned_card_no_fkey references public.cards_catalog(card_no) on delete cascade,
    copies integer not null default 1 constraint cards_owned_copies_check check (copies >= 1),
    first_at timestamptz not null default now(),
    last_at timestamptz not null default now(),
    favorite boolean not null default false,
    constraint cards_owned_pkey primary key (user_id, card_no)
  );
  create index if not exists cards_owned_last_idx on public.cards_owned (user_id, last_at desc);

  create table if not exists public.cards_packs (
    id uuid constraint cards_packs_pkey primary key default gen_random_uuid(),
    user_id uuid not null constraint cards_packs_user_id_fkey references auth.users(id) on delete cascade,
    source text not null constraint cards_packs_source_check check (source in ('stock', 'ad', 'shards', 'bonus')),
    cards integer[] not null constraint cards_packs_cards_check check (cardinality(cards) = 5),
    opened_at timestamptz not null default now()
  );
  create index if not exists cards_packs_user_idx on public.cards_packs (user_id, opened_at desc);

  create table if not exists public.cards_ad_tickets (
    id uuid constraint cards_ad_tickets_pkey primary key default gen_random_uuid(),
    user_id uuid not null constraint cards_ad_tickets_user_id_fkey references auth.users(id) on delete cascade,
    issued_at timestamptz not null default now(),
    used_at timestamptz
  );
  create index if not exists cards_ad_tickets_user_idx on public.cards_ad_tickets (user_id, issued_at desc);

  create table if not exists public.cards_reports (
    id bigint generated always as identity constraint cards_reports_pkey primary key,
    photo_id bigint constraint cards_reports_photo_id_fkey references public.cards_photos(id) on delete set null,
    card_no integer,
    role text not null constraint cards_reports_role_check check (role in ('person', 'photographer', 'agency', 'other')),
    message text not null constraint cards_reports_message_check check (length(btrim(message)) between 1 and 2000),
    -- Optional; kept until the report is closed, then erased (decision 6, trigger in 002).
    contact text constraint cards_reports_contact_check check (contact is null or length(contact) <= 200),
    created_at timestamptz not null default now(),
    status text not null default 'open' constraint cards_reports_status_check check (status in ('open', 'closed')),
    closed_at timestamptz
  );
  create index if not exists cards_reports_status_idx on public.cards_reports (status, created_at);

  if (select count(*) from information_schema.tables where table_schema = 'public' and table_name like 'cards\_%') <> 8 then
    raise exception '001-schema: the 8 cards tables are not all there';
  end if;
end $c001$;
