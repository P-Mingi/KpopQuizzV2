-- What:   the table character_game_facts (RLS on, no policy, closed to anon and authenticated like character_facts of 023), the two source views
--         dle_src_otakudle_one_piece and dle_src_otakudle_dragon_ball (closed to the browser roles, security_invoker), and the two game rows
--         otakudle-one-piece (page /otakudle/one-piece) and otakudle-dragon-ball (page /otakudle/dragon-ball) with their columns, switched off
--         (active false, no epoch, no bank). Nothing is shown to players. The engine of 019 is used as it is: its kinds single, multi, number and
--         ordinal cover every column (a set that overlaps is "near" in a multi, a number with no near distance gives its arrow, an
--         ordinal gives its arrow too), so 019 does not change.
--         One facts table for the per-series games: (character_id, game_id) -> attrs (the columns as {"v": value, "p": parents, "l": label}, the
--         shape of 020 and 023), hints (the secret clues), can_be_target. The data is the file launch/L15-A2-series-games.sql (generated by
--         scripts/anime/a2/gen-sql.mjs); the views only turn it into the shape the engine reads. "l" is the words to show when the stored value is a
--         number that stands for something (an arc or a saga order, a series order, "No bounty" for 0); the comparison never reads it.
--         One Piece, 8 columns: gender (single), affiliation (multi: one crew in common is near), devil_fruit_type (single: Paramecia, Zoan, Logia, none),
--         haki (multi: observation, armament, conqueror; none is the value of a character with no haki; sets that overlap are near), bounty
--         (number, arrows; "no bounty" is the value 0), height_cm (number, arrows), sea_of_origin (single), debut_arc (ordinal: the order of the arc, arrows).
--         Hints: the Devil Fruit name after 5 errors ("No Devil Fruit" for a character who has none, owner decision), the initial after 10.
--         Dragon Ball, 8 columns: gender (single), race (single), affiliation (multi), home_planet (single), universe (number), debut_series (ordinal:
--         DB 1, Z 2, GT 3, Super 4, Daima 5), debut_saga (ordinal: the order across all series), alignment_at_debut (single: good or evil). No height
--         (owner decision of 2026-11-03: too few heights, the column is removed). Hints: at 5 errors the signature technique when the character has one,
--         else the Japanese voice actor (the view puts exactly one of the two keys in hints, so the hint is never empty; both keys open at 5 and the
--         engine serves the one that is there); the initial at 10 (hint_keys {signature_technique,voice_actor_ja,initial}, hint_after {5,5,10}).
--         The pool of a view: the characters the facts table holds for the game, published, in a published series of the game (groups.slug
--         one-piece or dragon-ball, site anime). Neither characters.spoiler_level nor identity_spoiler excludes a character (owner, 2026-11-02, CR-023:
--         only the columns describe the character as first met). The facts stop at the reference point of the data (One Piece: the Egghead arc, the
--         last arc finished in the anime; Dragon Ball: Daima), and a player picks the series game knowing the series.
--         can_be_target: the flag of the facts row (the generator sets it only when every column and the 5-error hint have a value; a Dragon Ball
--         character with neither a technique nor a voice actor is not a target) and the hint present,
--         and the engine requires every column of dle_attributes to hold a value. A picture only when entity_images (site anime, kind character,
--         slug "<series>/<character>") has license_verified and a 96 px thumb_path; otherwise null and the client shows the initials.
--         balance_key: the arc (One Piece) or the saga (Dragon Ball) of the debut, so two days in a row rarely ask for the same part of the story.
-- Height: One Piece keeps height_cm, with a single Fandom source accepted for that column (owner exception to the two-source rule, 2026-11-03).
--         Dragon Ball has none. The view carries whatever attrs the facts hold, the comparison reads dle_attributes only, and the generator of L15 reads
--         the column list from the dle_attributes insert below, so a column is added or dropped by that one line.
-- Why:    owner decision of 2026-11-02: two daily games of one series, One Piece and Dragon Ball, as pages /otakudle/one-piece and /otakudle/dragon-ball.
-- When:   session G, right after 023: the table and the views. The game rows need the anime row of public.sites (dle_games.universe), which only L01
--         adds on launch day, so while that row is missing this file leaves the games out; session.sh J4 runs the file again after 023 and the game
--         rows are added then. The facts are launch/L15-A2-series-games.sql (J4, after L13); activation is launch/L14-O1-dle-on.sql, never this file.
-- Rows:   none in session G; in J4, 2 dle_games rows and 16 dle_attributes rows (8 and 8).
-- Needs:  011-anime-series.sql, 018-entity-images.sql, 019-dle-core.sql.
-- Verify: docs/launch/o1/checks/V-024.sql (session.sh G and J4)
