-- The facts of the per-series games. No foreign key to dle_games: the facts table is made in session G, the game rows only once L01 added the anime site.
create table if not exists public.character_game_facts (
  character_id integer not null references public.characters(id) on delete cascade,
  game_id text not null constraint character_game_facts_game_id_check check (game_id ~ '^[a-z0-9][a-z0-9-]{1,40}$'),
  attrs jsonb not null constraint character_game_facts_attrs_check check (jsonb_typeof(attrs) = 'object'),
  hints jsonb not null default '{}' constraint character_game_facts_hints_check check (jsonb_typeof(hints) = 'object'),
  can_be_target boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint character_game_facts_pkey primary key (character_id, game_id)
);

alter table public.character_game_facts enable row level security;

-- Supabase grants every new table to anon and authenticated by default: the browser reads the pool only through dle_pool.
revoke all on table public.character_game_facts from public, anon, authenticated;
grant all on table public.character_game_facts to service_role;

-- One Piece. devil_fruit_name hint: the name stored in the facts, or "No Devil Fruit" for a character whose type is none (owner decision).
create or replace view public.dle_src_otakudle_one_piece with (security_invoker = true) as
select
  c.id::text as entity_id,
  c.name,
  array(select distinct n from unnest(array[c.name, c.name_native] || c.aliases) as n where nullif(btrim(n), '') is not null) as search,
  f.attrs,
  jsonb_strip_nulls(jsonb_build_object(
    'devil_fruit_name', case when f.attrs -> 'devil_fruit_type' ->> 'v' = 'none' then 'No Devil Fruit' else nullif(btrim(f.hints ->> 'devil_fruit_name'), '') end,
    'initial', upper(left(c.name, 1)))) as hints,
  (select ei.thumb_path from public.entity_images ei
    where ei.site_id = 'anime' and ei.kind = 'character' and ei.slug = g.slug || '/' || c.slug and ei.license_verified and ei.thumb_path is not null) as thumb_path,
  f.attrs -> 'debut_arc' ->> 'l' as balance_key,
  f.can_be_target
    and (f.attrs -> 'devil_fruit_type' ->> 'v' = 'none' or nullif(btrim(f.hints ->> 'devil_fruit_name'), '') is not null) as can_be_target
from public.character_game_facts f
join public.characters c on c.id = f.character_id
join public.groups g on g.id = c.group_id and g.site_id = 'anime' and g.slug = 'one-piece'
join public.series s on s.group_id = g.id and s.published
where f.game_id = 'otakudle-one-piece' and c.status = 'published';

-- Dragon Ball. The 5-error hint: the signature technique, else the Japanese voice actor, never both (the facts may hold both).
create or replace view public.dle_src_otakudle_dragon_ball with (security_invoker = true) as
select
  c.id::text as entity_id,
  c.name,
  array(select distinct n from unnest(array[c.name, c.name_native] || c.aliases) as n where nullif(btrim(n), '') is not null) as search,
  f.attrs,
  jsonb_strip_nulls(jsonb_build_object(
    'signature_technique', nullif(btrim(f.hints ->> 'signature_technique'), ''),
    'voice_actor_ja', case when nullif(btrim(f.hints ->> 'signature_technique'), '') is null then nullif(btrim(f.hints ->> 'voice_actor_ja'), '') end,
    'initial', upper(left(c.name, 1)))) as hints,
  (select ei.thumb_path from public.entity_images ei
    where ei.site_id = 'anime' and ei.kind = 'character' and ei.slug = g.slug || '/' || c.slug and ei.license_verified and ei.thumb_path is not null) as thumb_path,
  f.attrs -> 'debut_saga' ->> 'l' as balance_key,
  f.can_be_target
    and (nullif(btrim(f.hints ->> 'signature_technique'), '') is not null or nullif(btrim(f.hints ->> 'voice_actor_ja'), '') is not null) as can_be_target
from public.character_game_facts f
join public.characters c on c.id = f.character_id
join public.groups g on g.id = c.group_id and g.site_id = 'anime' and g.slug = 'dragon-ball'
join public.series s on s.group_id = g.id and s.published
where f.game_id = 'otakudle-dragon-ball' and c.status = 'published';

-- A view is readable by anon and authenticated by default on Supabase and runs with its owner's rights unless security_invoker:
-- only the dle functions (as their owner) and the service role read them.
revoke all on table public.dle_src_otakudle_one_piece, public.dle_src_otakudle_dragon_ball from public, anon, authenticated;
grant select on table public.dle_src_otakudle_one_piece, public.dle_src_otakudle_dragon_ball to service_role;

-- no_repeat_days is 120, the standard of the other games (CR-019: the bank of 019 now builds for every pool size, so the 30 and 14 that avoided
-- its random failures are gone; the window is min(120, 70 % of the targets), 21 days at the minimum pool of 30).
-- The games: only once L01 added the anime site (dle_games.universe). Never touches a row that is already there, so a run after the activation changes nothing.
insert into public.dle_games (id, universe, entity_kind, source_view, no_repeat_days, min_pool, hint_keys, hint_after, active)
select g.id, 'anime', 'character', g.source_view, g.no_repeat_days, g.min_pool, g.hint_keys, g.hint_after, false
from (values
  ('otakudle-one-piece', 'dle_src_otakudle_one_piece', 120, 40, '{devil_fruit_name,initial}'::text[], '{5,10}'::integer[]),
  ('otakudle-dragon-ball', 'dle_src_otakudle_dragon_ball', 120, 30, '{signature_technique,voice_actor_ja,initial}'::text[], '{5,5,10}'::integer[])
) as g(id, source_view, no_repeat_days, min_pool, hint_keys, hint_after)
where exists (select 1 from public.sites where id = 'anime')
on conflict (id) do nothing;

-- The columns. The generator of L15 reads this list: a column is in the data only when it is a line here.
insert into public.dle_attributes (game_id, key, kind, position, near)
select a.game_id, a.key, a.kind, a.position, a.near
from (values
  ('otakudle-one-piece', 'gender', 'single', 1::smallint, null::numeric),
  ('otakudle-one-piece', 'affiliation', 'multi', 2::smallint, null::numeric),
  ('otakudle-one-piece', 'devil_fruit_type', 'single', 3::smallint, null::numeric),
  ('otakudle-one-piece', 'haki', 'multi', 4::smallint, null::numeric),
  ('otakudle-one-piece', 'bounty', 'number', 5::smallint, null::numeric),
  ('otakudle-one-piece', 'height_cm', 'number', 6::smallint, null::numeric),
  ('otakudle-one-piece', 'sea_of_origin', 'single', 7::smallint, null::numeric),
  ('otakudle-one-piece', 'debut_arc', 'ordinal', 8::smallint, null::numeric),
  ('otakudle-dragon-ball', 'gender', 'single', 1::smallint, null::numeric),
  ('otakudle-dragon-ball', 'race', 'single', 2::smallint, null::numeric),
  ('otakudle-dragon-ball', 'affiliation', 'multi', 3::smallint, null::numeric),
  ('otakudle-dragon-ball', 'home_planet', 'single', 4::smallint, null::numeric),
  ('otakudle-dragon-ball', 'universe', 'number', 5::smallint, null::numeric),
  ('otakudle-dragon-ball', 'debut_series', 'ordinal', 6::smallint, null::numeric),
  ('otakudle-dragon-ball', 'debut_saga', 'ordinal', 7::smallint, null::numeric),
  ('otakudle-dragon-ball', 'alignment_at_debut', 'single', 8::smallint, null::numeric)
) as a(game_id, key, kind, position, near)
where exists (select 1 from public.dle_games g where g.id = a.game_id)
on conflict (game_id, key) do nothing;

-- Self-check: closed to the browser roles, the games (when they are there) complete, the published rule in the views.
do $$
declare
  n integer;
begin
  if has_table_privilege('anon', 'public.character_game_facts', 'select') or has_table_privilege('authenticated', 'public.character_game_facts', 'select')
    or has_table_privilege('anon', 'public.character_game_facts', 'insert') or has_table_privilege('authenticated', 'public.character_game_facts', 'insert') then
    raise exception '024-dle-series-games: character_game_facts is reachable by a browser role';
  end if;
  if exists (select 1 from pg_policy where polrelid = 'public.character_game_facts'::regclass) then
    raise exception '024-dle-series-games: character_game_facts has a policy';
  end if;
  if has_table_privilege('anon', 'public.dle_src_otakudle_one_piece', 'select') or has_table_privilege('authenticated', 'public.dle_src_otakudle_one_piece', 'select')
    or has_table_privilege('anon', 'public.dle_src_otakudle_dragon_ball', 'select') or has_table_privilege('authenticated', 'public.dle_src_otakudle_dragon_ball', 'select') then
    raise exception '024-dle-series-games: a source view is readable by a browser role';
  end if;
  if exists (select 1 from public.dle_games where id = 'otakudle-one-piece') then
    select count(*) into n from public.dle_attributes where game_id = 'otakudle-one-piece';
    if n <> 8 then
      raise exception '024-dle-series-games: otakudle-one-piece does not have 8 columns (%)', n;
    end if;
  end if;
  if exists (select 1 from public.dle_games where id = 'otakudle-dragon-ball') then
    select count(*) into n from public.dle_attributes where game_id = 'otakudle-dragon-ball';
    if n <> 8 then
      raise exception '024-dle-series-games: otakudle-dragon-ball does not have 8 columns (%)', n;
    end if;
  end if;
  if pg_get_viewdef('public.dle_src_otakudle_one_piece'::regclass) !~ 'published' or pg_get_viewdef('public.dle_src_otakudle_dragon_ball'::regclass) !~ 'published'
    or pg_get_viewdef('public.dle_src_otakudle_one_piece'::regclass) ~ 'identity_spoiler|spoiler_level' or pg_get_viewdef('public.dle_src_otakudle_dragon_ball'::regclass) ~ 'identity_spoiler|spoiler_level' then
    raise exception '024-dle-series-games: a view lost its published rule, or filters on a spoiler';
  end if;
end $$;

