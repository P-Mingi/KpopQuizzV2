// node apps/quiz/e2e/o1/L1/anime-bank-lot1-sql.mjs   (writes L29-l1-anime-bank-lot1.sql and its .rollback.sql; never hand-edited)
// Reads the L08 values from docs/anime/data/daily/b1.json and b2.json (what production holds) and the verified lot from
// docs/anime/data/verify/bank-lot1.json. No database, no network.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../..');
const LAUNCH = `${REPO}/docs/pending-migrations/multisite/launch`;
export const WINDOW = { from: '2026-11-21', to: '2026-12-21' };

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const dq = (s) => {
  if (String(s).includes('$o1q$')) throw new Error('dollar tag clash');
  return `$o1q$${s}$o1q$`;
};

export function load() {
  const l08 = [...JSON.parse(readFileSync(`${REPO}/docs/anime/data/daily/b1.json`, 'utf8')), ...JSON.parse(readFileSync(`${REPO}/docs/anime/data/daily/b2.json`, 'utf8'))];
  const lot = JSON.parse(readFileSync(`${REPO}/docs/anime/data/verify/bank-lot1.json`, 'utf8'));
  return { l08, lot };
}

export function rows({ l08, lot }) {
  const byTitle = new Map(l08.map((r) => [r.title, r]));
  return lot.quizzes.map((q) => {
    const old = byTitle.get(q.l08_title);
    if (!old) throw new Error(`not an L08 row: ${q.l08_title}`);
    const urls = [...new Set(q.questions.map((x) => x.source_url))];
    return { l08_title: q.l08_title, title: q.title, description: q.description, date: q.date, oldQuestions: old.questions, questions: q.questions, urls };
  });
}

const key = (c) => `md5(lower(btrim(${c})))`;

export function build({ l08, lot }) {
  const rs = rows({ l08, lot });
  const N = rs.length;
  const moved = lot.moved_row;
  const first = rs[0].date, last = rs.at(-1).date;
  const notesHead = `Anime daily bank lot 1 (L29). Each question re-read on ${lot.read_on} against its cited page, see docs/anime/data/verify/bank-lot1.json and bank-lot1.md; owner review packet docs/anime/editorial/packets/bank-lot1.html. Drafted with AI assistance, checked by `;
  const values = rs.map((r) => `  (${sq(r.l08_title)}, ${sq(r.title)}, ${sq(r.description)}, ${sq(r.date)}::date, ${dq(JSON.stringify(r.questions))}::jsonb, ${dq(JSON.stringify(r.oldQuestions))}::jsonb, ${sq(`Sources: ${r.urls.join(' ; ')}. `)})`).join(',\n');
  const titlesNew = rs.map((r) => sq(r.title.toLowerCase().trim())).join(', ');
  const titlesOld = rs.map((r) => sq(r.l08_title.toLowerCase().trim())).join(', ');

  const sql = `-- L29-l1-anime-bank-lot1.sql (run O1, lane animebank, owner request 2026-11-09; generated by apps/quiz/e2e/o1/L1/anime-bank-lot1-sql.mjs, do not edit by hand)
--
-- What:   files ${N} of the 85 L08 anime drafts as verified, scheduled daily quizzes, one a day from ${first} to ${last} (each question re-read from its
--         cited page and fixed or replaced where needed: docs/anime/data/verify/bank-lot1.json), and moves the stuck row ${sq(moved.title)}
--         from ${moved.from} (never published: the anime cron had not reached otakuquiz) to ${moved.to}. Per row: questions (and title or description when fixed),
--         status 'scheduled', scheduled_date, verified_at = now(), verification_notes. Nothing else: no group, no other row, no kpop row.
--         ${N} of the 30 planned days are filled (the second reading carried ${N} quizzes clean of duplicates; the free slots are ${addDays(moved.to, 1)} to ${WINDOW.to}, after the moved row).
-- Needs:  L08 (the 99 draft rows), 009 and 010 (quiz_bank_site_date, per-site daily), L04 (anime groups). The owner fills {REVIEWER} and {REVIEW_DATE} in the one review line below after his review:
--         while they are unfilled the file refuses to apply.
-- WHEN:   after a backup, outside a build, never between 23:50 and 00:30 UTC, and before the evening of 2026-11-20 (the anime daily runs out after 2026-11-20).
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and status = 'scheduled' and scheduled_date between '${first}' and '${last}';   expect ${N}
--         select scheduled_date from public.quiz_bank where site_id = 'anime' and title = ${sq(moved.title)};   expect ${moved.to}
--         select count(*) from public.quiz_bank where site_id = 'anime' and status = 'draft';   expect ${85 - N} (the 85 L08 drafts less the ${N} filed here, if none was touched before)
-- Undo:   L29-l1-anime-bank-lot1.rollback.sql (exact L08 values back, refused once one of these rows is published).
-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing. A row changed since L08 is left alone and makes the self-check fail.

set lock_timeout = '5s';
set client_min_messages = warning;

create temp table _l29_review (reviewer text, review_date text) on commit drop;
insert into _l29_review values ('{REVIEWER}', '{REVIEW_DATE}');

do $o1l$ begin
  if exists (select 1 from _l29_review where reviewer ~ '[{](REVIEWER|REVIEW_DATE)[}]' or review_date ~ '[{](REVIEWER|REVIEW_DATE)[}]') then
    raise exception 'L29: review not recorded (replace {REVIEWER} and {REVIEW_DATE} in the _l29_review line), nothing applied';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'quiz_bank' and column_name = 'site_id') then
    raise exception 'L29: quiz_bank.site_id is missing (apply 002a first)';
  end if;
  if not exists (select 1 from pg_indexes where schemaname = 'public' and indexname = 'quiz_bank_site_date') then
    raise exception 'L29: quiz_bank_site_date is missing (apply 009 and 010 first)';
  end if;
end $o1l$;

create temp table _l29 (l08_title text, title text, description text, scheduled_date date, questions jsonb, old_questions jsonb, notes_sources text) on commit drop;

insert into _l29 values
${values};

do $o1l$ declare n int; applied int; m int; moved_done int; begin
  -- Refuse if another anime row is already scheduled in the window (a lot row already in its place and the moved row do not count).
  if exists (
    select 1 from public.quiz_bank b
    where b.site_id = 'anime' and b.scheduled_date between '${WINDOW.from}' and '${WINDOW.to}' and b.status in ('scheduled', 'verified', 'published')
      and not exists (select 1 from _l29 v where ${key('b.title')} in (${key('v.title')}, ${key('v.l08_title')}) and b.scheduled_date = v.scheduled_date)
      and not (${key('b.title')} = md5(${sq(moved.title.toLowerCase().trim())}) and b.scheduled_date = '${moved.to}')
  ) then
    raise exception 'L29: another anime row is already scheduled between ${WINDOW.from} and ${WINDOW.to}, nothing applied';
  end if;

  -- The ${N} lot rows, only while still in their L08 state.
  update public.quiz_bank b set
    title = v.title, description = v.description, questions = v.questions, status = 'scheduled', scheduled_date = v.scheduled_date,
    verified_at = now(), verification_notes = v.notes_sources || ${sq(notesHead)} || r.reviewer || ' on ' || r.review_date || '.', updated_at = now()
  from _l29 v cross join _l29_review r
  where b.site_id = 'anime' and ${key('b.title')} = ${key('v.l08_title')}
    and b.status = 'draft' and b.scheduled_date is null and b.verified_at is null and b.published_quiz_id is null and b.questions = v.old_questions;
  get diagnostics n = row_count;

  -- The stuck row, only while scheduled on ${moved.from} and unpublished.
  update public.quiz_bank b set scheduled_date = '${moved.to}', updated_at = now()
  where b.site_id = 'anime' and ${key('b.title')} = md5(${sq(moved.title.toLowerCase().trim())})
    and b.status = 'scheduled' and b.scheduled_date = '${moved.from}' and b.published_quiz_id is null;
  get diagnostics m = row_count;

  select count(*) into applied from public.quiz_bank b join _l29 v on ${key('b.title')} = ${key('v.title')}
    where b.site_id = 'anime' and b.status = 'scheduled' and b.scheduled_date = v.scheduled_date and b.questions = v.questions and b.published_quiz_id is null;
  select count(*) into moved_done from public.quiz_bank b
    where b.site_id = 'anime' and ${key('b.title')} = md5(${sq(moved.title.toLowerCase().trim())}) and b.status = 'scheduled' and b.scheduled_date = '${moved.to}' and b.published_quiz_id is null;

  -- Self-check: exactly ${N} lot rows changed plus the moved row (or a second run: none), and every lot row is in its final state.
  if not ((n = ${N} and m in (0, 1)) or (n = 0 and m = 0)) or applied <> ${N} or moved_done <> 1 then
    raise exception 'L29 self-check failed: % lot rows changed (expected ${N} or 0), % in final state (expected ${N}), moved row changed %, moved row in place % (expected 1); a row changed since L08 or published, nothing applied', n, applied, m, moved_done;
  end if;
end $o1l$;
`;

  const rollback = `-- L29-l1-anime-bank-lot1.rollback.sql (run O1, lane animebank; generated by apps/quiz/e2e/o1/L1/anime-bank-lot1-sql.mjs, do not edit by hand)
--
-- What:   undoes L29. The ${N} lot rows go back to their exact L08 values (title, description, questions, status draft, no date, no verification, no notes)
--         and the row ${sq(moved.title)} goes back to ${moved.from}. Refused while one of these rows is published. Idempotent.
-- o1-transaction: single (psql --single-transaction).

set lock_timeout = '5s';
set client_min_messages = warning;

create temp table _l29 (l08_title text, title text, description text, scheduled_date date, old_description text, old_questions jsonb) on commit drop;

insert into _l29 values
${rs.map((r) => `  (${sq(r.l08_title)}, ${sq(r.title)}, ${sq(r.description)}, ${sq(r.date)}::date, ${sq(l08.find((x) => x.title === r.l08_title).description)}, ${dq(JSON.stringify(r.oldQuestions))}::jsonb)`).join(',\n')};

do $o1l$ declare n int; m int; begin
  if exists (
    select 1 from public.quiz_bank b join _l29 v on ${key('b.title')} in (${key('v.title')}, ${key('v.l08_title')})
    where b.site_id = 'anime' and (b.status = 'published' or b.published_quiz_id is not null) and b.scheduled_date = v.scheduled_date
  ) or exists (
    select 1 from public.quiz_bank b
    where b.site_id = 'anime' and ${key('b.title')} = md5(${sq(moved.title.toLowerCase().trim())}) and b.scheduled_date = '${moved.to}' and (b.status = 'published' or b.published_quiz_id is not null)
  ) then
    raise exception 'L29 rollback refused: a row of the lot or the moved row is already published';
  end if;

  update public.quiz_bank b set title = v.l08_title, description = v.old_description, questions = v.old_questions, status = 'draft', scheduled_date = null,
    verified_at = null, verification_notes = null, updated_at = now()
  from _l29 v
  where b.site_id = 'anime' and ${key('b.title')} in (${key('v.title')}, ${key('v.l08_title')})
    and b.status = 'scheduled' and b.scheduled_date = v.scheduled_date and b.published_quiz_id is null;
  get diagnostics n = row_count;

  update public.quiz_bank b set scheduled_date = '${moved.from}', updated_at = now()
  where b.site_id = 'anime' and ${key('b.title')} = md5(${sq(moved.title.toLowerCase().trim())})
    and b.status = 'scheduled' and b.scheduled_date = '${moved.to}' and b.published_quiz_id is null;
  get diagnostics m = row_count;

  if n not in (0, ${N}) or m not in (0, 1) or (n = ${N} and m <> 1) then
    raise exception 'L29 rollback self-check failed: % lot rows restored (expected ${N} or 0), moved row restored % (expected 1 with the lot)', n, m;
  end if;
end $o1l$;
`;
  return { sql, rollback, N, first, last };
}

function addDays(iso, n) { return new Date(Date.parse(`${iso}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10); }

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sql, rollback, N } = build(load());
  writeFileSync(`${LAUNCH}/L29-l1-anime-bank-lot1.sql`, sql);
  writeFileSync(`${LAUNCH}/L29-l1-anime-bank-lot1.rollback.sql`, rollback);
  console.log(`L29 written: ${N} rows`);
}
