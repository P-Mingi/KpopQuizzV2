// node apps/quiz/e2e/o1/L1/anime-bank-lot2-sql.mjs   (writes L30-l1-anime-bank-lot2.sql and its .rollback.sql; never hand-edited)
// Reads the L08 values from docs/anime/data/daily/b1.json and b2.json (what production holds) and the verified lot from
// docs/anime/data/verify/bank-lot2.json. No database, no network. One DO block per file, no temp table.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../..');
const LAUNCH = `${REPO}/docs/pending-migrations/multisite/launch`;

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const dq = (s) => {
  if (String(s).includes('$o1q$')) throw new Error('dollar tag clash');
  return `$o1q$${s}$o1q$`;
};

export function load() {
  const l08 = [...JSON.parse(readFileSync(`${REPO}/docs/anime/data/daily/b1.json`, 'utf8')), ...JSON.parse(readFileSync(`${REPO}/docs/anime/data/daily/b2.json`, 'utf8'))];
  const lot = JSON.parse(readFileSync(`${REPO}/docs/anime/data/verify/bank-lot2.json`, 'utf8'));
  const lot1 = JSON.parse(readFileSync(`${REPO}/docs/anime/data/verify/bank-lot1.json`, 'utf8'));
  return { l08, lot, lot1 };
}

export function rows({ l08, lot }) {
  const byTitle = new Map(l08.map((r) => [r.title, r]));
  return lot.quizzes.map((q) => {
    const old = byTitle.get(q.l08_title);
    if (!old) throw new Error(`not an L08 row: ${q.l08_title}`);
    const src = [...new Set(q.verdicts.map((v) => `${q.questions[v.position].source_url} (rev ${v.revision})`))];
    return { l08_title: q.l08_title, title: q.title, description: q.description, date: q.date, old_description: old.description, old_questions: old.questions, questions: q.questions, src };
  });
}

const key = (c) => `lower(btrim(${c}))`;

export function build({ l08, lot, lot1 }) {
  const rs = rows({ l08, lot });
  const N = rs.length;
  const first = rs[0].date, last = rs.at(-1).date;
  // the L08 drafts that stay drafts after this lot (not in lot 1, not in lot 2, not a taken row): used by the Verify lines
  const used1 = new Set(lot1.quizzes.map((q) => q.l08_title)), used2 = new Set(rs.map((r) => r.l08_title));
  const taken = new Set(['Name That Series: Deep Cuts', 'Sessions in the Solar System: True or False', 'Stand Proud: Facts From the Joestar Archive', 'Naruto Endings: Roll the Credits', 'Directors, Awards and Theme Songs', 'Rank E True or False', 'Dragon Ball Jukebox: Openings and Endings', 'One Punch Statements: True or False', 'Closing Credits: Ending Song Quiz', 'Soul Reaper Statements: True or False', 'From Web Novel to Webtoon to Film', 'Name That Series: Studios, Songs and Staff', 'From 1984 to Daima: Dragon Ball by the Calendar', 'Rank E and the Web Novel Behind It']);
  const pool = l08.filter((r) => !used1.has(r.title) && !taken.has(r.title)).map((r) => r.title); // the 58 drafts left after lot 1
  const left = pool.filter((t) => !used2.has(t));
  const notesHead = (r) => `Sources: ${r.src.join(' ; ')}. Anime daily bank lot 2 (L30). Each question re-read on ${lot.read_on} against its cited Wikipedia page at a pinned revision, see docs/anime/data/verify/bank-lot2.json and bank-lot2.md; three independent readings recorded there; owner review packet docs/anime/editorial/packets/bank-lot2.html. Drafted with AI assistance, checked by `;
  const json = JSON.stringify(rs.map((r) => ({ l08_title: r.l08_title, title: r.title, description: r.description, date: r.date, notes: notesHead(r), questions: r.questions, old_questions: r.old_questions })));
  const inList = (xs) => xs.map(sq).join(', ');
  const lastRow = rs.at(-1), firstRow = rs[0];

  const sql = `-- L30-l1-anime-bank-lot2.sql (run O1, lane animebank, lot 2; generated by apps/quiz/e2e/o1/L1/anime-bank-lot2-sql.mjs, do not edit by hand)
--
-- What:   files ${N} of the 58 L08 anime drafts left after lot 1 (L29) as verified, scheduled daily quizzes, one a day from ${first} to ${last}. Almost every draft question repeated a fact
--         already asked, so the quizzes are rebuilt on new sourced questions (each re-read at a pinned Wikipedia revision, three readings: docs/anime/data/verify/bank-lot2.json, bank-lot2.md).
--         Per row: title, description, questions, status 'scheduled', scheduled_date, verified_at = now(), verification_notes. Nothing else: no group, no other row, no kpop row.
-- Needs:  L08 (the draft rows) and L29 (lot 1 filed 2026-11-21 to 2026-12-18). This is data only: it can be applied before the code of the final merge. The owner fills {REVIEWER} and {REVIEW_DATE}
--         (two constants at the top of the block) after the review: while they are unfilled the file refuses to apply.
-- WHEN:   after a backup, outside a build, never between 23:50 and 00:30 UTC, well before ${addDays(first, -2)} (the anime daily would otherwise run out after 2026-12-18).
-- Refuses: while the review constants are unfilled; if any anime row already has a scheduled_date from ${first} to ${last} (other than these rows in their final state); if a row is no longer in its exact L08 state
--         (status draft, no date, not verified, not published, same questions); the self-check raises unless exactly ${N} rows changed (a second run changes none). One DO block, so a raise applies nothing.
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and status = 'scheduled' and scheduled_date between '${first}' and '${last}' and verified_at is not null and published_quiz_id is null;   expect ${N}
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date between '${first}' and '${last}' and verification_notes like '%(L30)%' and jsonb_array_length(questions) = 8;   expect ${N}
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date = '${first}' and title = ${sq(firstRow.title)};   expect 1
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date = '${last}' and title = ${sq(lastRow.title)};   expect 1
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and status = 'draft' and scheduled_date is null and title in (${inList(left)});   expect ${left.length} (the ${pool.length} drafts left after lot 1, less the ${N} filed here)
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date between '2026-11-21' and '2026-12-18';   expect ${lot1.quizzes.length + 1} (lot 1 and the moved row, untouched)
-- Undo:   L30-l1-anime-bank-lot2.rollback.sql (exact L08 values back, refused once one of these rows is published).
-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing.

do $o1l$
declare
  v_reviewer text := '{REVIEWER}';
  v_review_date text := '{REVIEW_DATE}';
  v_rows jsonb := ${dq(json)}::jsonb;
  r jsonb;
  n int := 0;
  step int;
  applied int;
begin
  perform set_config('lock_timeout', '5s', true);
  if v_reviewer ~ '[{](REVIEWER|REVIEW_DATE)[}]' or v_review_date ~ '[{](REVIEWER|REVIEW_DATE)[}]' then
    raise exception 'L30: review not recorded (replace {REVIEWER} and {REVIEW_DATE} at the top of the block), nothing applied';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'quiz_bank' and column_name = 'site_id') then
    raise exception 'L30: quiz_bank.site_id is missing (apply 002a first)';
  end if;
  if not exists (select 1 from pg_indexes where schemaname = 'public' and indexname = 'quiz_bank_site_date') then
    raise exception 'L30: quiz_bank_site_date is missing (apply 009 and 010 first)';
  end if;

  -- Refuse if another anime row already holds a date of the lot (a lot row already in its final place does not count).
  if exists (
    select 1 from public.quiz_bank b
    where b.site_id = 'anime' and b.scheduled_date between '${first}' and '${last}'
      and not exists (select 1 from jsonb_array_elements(v_rows) e where ${key('b.title')} = ${key("e->>'title'")} and b.scheduled_date = (e->>'date')::date)
  ) then
    raise exception 'L30: another anime row already has a scheduled_date between ${first} and ${last}, nothing applied';
  end if;

  -- The ${N} lot rows, only while still in their exact L08 state.
  for r in select e from jsonb_array_elements(v_rows) e loop
    update public.quiz_bank b set
      title = r->>'title', description = r->>'description', questions = r->'questions', status = 'scheduled', scheduled_date = (r->>'date')::date,
      verified_at = now(), verification_notes = (r->>'notes') || v_reviewer || ' on ' || v_review_date || '.', updated_at = now()
    where b.site_id = 'anime' and ${key('b.title')} = ${key("r->>'l08_title'")}
      and b.status = 'draft' and b.scheduled_date is null and b.verified_at is null and b.published_quiz_id is null and b.questions = (r->'old_questions');
    get diagnostics step = row_count;
    n := n + step;
  end loop;

  select count(*) into applied from jsonb_array_elements(v_rows) e join public.quiz_bank b on ${key('b.title')} = ${key("e->>'title'")}
    where b.site_id = 'anime' and b.status = 'scheduled' and b.scheduled_date = (e->>'date')::date and b.questions = (e->'questions') and b.published_quiz_id is null;

  -- Self-check: exactly ${N} rows changed (or a second run: none), and every lot row is in its final state.
  if not (n in (0, ${N})) or applied <> ${N} then
    raise exception 'L30 self-check failed: % rows changed (expected ${N} or 0), % in final state (expected ${N}); a row changed since L08 or published, nothing applied', n, applied;
  end if;
end $o1l$;
`;

  const rollback = `-- L30-l1-anime-bank-lot2.rollback.sql (run O1, lane animebank; generated by apps/quiz/e2e/o1/L1/anime-bank-lot2-sql.mjs, do not edit by hand)
--
-- What:   undoes L30. The ${N} lot rows go back to their exact L08 values (title, description, questions, status draft, no date, no verification, no notes).
--         Refused while one of these rows is published. Idempotent. One DO block, so a raise applies nothing.
-- WHEN:   after a backup, outside a build, never between 23:50 and 00:30 UTC.
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date between '${first}' and '${last}';   expect 0
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and status = 'draft' and scheduled_date is null and verified_at is null and verification_notes is null and title in (${inList(pool)});   expect ${pool.length}
-- Verify: select count(*) from public.quiz_bank where site_id = 'anime' and scheduled_date between '2026-11-21' and '2026-12-18';   expect ${lot1.quizzes.length + 1} (lot 1 and the moved row, untouched)
-- o1-transaction: single (psql --single-transaction).

do $o1l$
declare
  v_rows jsonb := ${dq(JSON.stringify(rs.map((r) => ({ l08_title: r.l08_title, title: r.title, date: r.date, old_description: r.old_description, old_questions: r.old_questions }))))}::jsonb;
  r jsonb;
  n int := 0;
  step int;
begin
  perform set_config('lock_timeout', '5s', true);
  if exists (
    select 1 from jsonb_array_elements(v_rows) e join public.quiz_bank b on ${key('b.title')} in (${key("e->>'title'")}, ${key("e->>'l08_title'")})
    where b.site_id = 'anime' and b.scheduled_date = (e->>'date')::date and (b.status = 'published' or b.published_quiz_id is not null)
  ) then
    raise exception 'L30 rollback refused: a row of the lot is already published';
  end if;

  for r in select e from jsonb_array_elements(v_rows) e loop
    update public.quiz_bank b set title = r->>'l08_title', description = r->>'old_description', questions = r->'old_questions', status = 'draft', scheduled_date = null,
      verified_at = null, verification_notes = null, updated_at = now()
    where b.site_id = 'anime' and ${key('b.title')} in (${key("r->>'title'")}, ${key("r->>'l08_title'")})
      and b.status = 'scheduled' and b.scheduled_date = (r->>'date')::date and b.published_quiz_id is null;
    get diagnostics step = row_count;
    n := n + step;
  end loop;

  if n not in (0, ${N}) then
    raise exception 'L30 rollback self-check failed: % lot rows restored (expected ${N} or 0), nothing applied', n;
  end if;
end $o1l$;
`;
  return { sql, rollback, N, first, last, left, pool };
}

export function addDays(iso, n) { return new Date(Date.parse(`${iso}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10); }

// The owner's review is NOT recorded yet: build() keeps the placeholders and so does the committed file (it refuses to apply until filled).
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sql, rollback, N } = build(load());
  writeFileSync(`${LAUNCH}/L30-l1-anime-bank-lot2.sql`, sql);
  writeFileSync(`${LAUNCH}/L30-l1-anime-bank-lot2.rollback.sql`, rollback);
  console.log(`L30 written: ${N} rows`);
}
