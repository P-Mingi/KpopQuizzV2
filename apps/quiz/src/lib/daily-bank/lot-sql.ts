// The SQL of a reviewed daily quiz lot and its rollback (Mission U, owner 2026-10-15), written by
// scripts/daily-bank/to-sql.mts. The owner applies it himself, after his review. Kpop only (lot 2,
// owner 2026-10-25): the insert names no site_id, so after Run O1's 002a the column default 'kpop'
// fills it, a check stops the transaction if a row of the lot is on another site, and every other
// statement (date check, rollback) reads or deletes kpop rows only.

import { kpopRowSql } from './kpop-scope';

export interface McQuestion { question: string; options: string[]; correct: number; fun_fact: string; source: string }
export interface TfQuestion { question: string; correct: boolean; fun_fact: string; source: string }
export interface LotQuiz {
  scheduled_date: string;
  title: string;
  description: string;
  group_slug: string | null;
  category: 'group_specific' | 'knowledge' | 'era' | 'fun' | 'true_false';
  quiz_type: 'multiple_choice' | 'true_false';
  difficulty: 'easy' | 'medium' | 'hard';
  questions: Array<McQuestion | TfQuestion>;
  sources?: string[];
}

export interface LotSql { name: string; rollbackName: string; sql: string; rollback: string }

const sqlText = (s: string): string => `'${s.replace(/'/g, "''")}'`;

/**
 * `lot` sorted by date; `idOf` maps the kpop group slugs to their ids (a slug it does not know is
 * an error, so a group of another site can never be linked). Without a reviewer and a review date
 * the notes keep {REVIEWER} and {REVIEW_DATE} for the owner to fill.
 */
export function buildLotSql(lotN: string, lotIn: readonly LotQuiz[], idOf: ReadonlyMap<string, number>, reviewer?: string | null, reviewed?: string | null): LotSql {
  const lot = [...lotIn].sort((a, b) => a.scheduled_date.localeCompare(b.scheduled_date));
  if (lot.length === 0) throw new Error('empty lot');
  const review = reviewer && reviewed
    ? `Drafted with AI assistance, checked by ${reviewer} on ${reviewed}.`
    : 'Drafted with AI assistance, checked by {REVIEWER} on {REVIEW_DATE}.';

  const values = lot.map((q) => {
    const gid = q.group_slug ? idOf.get(q.group_slug) : null;
    if (q.group_slug && gid == null) throw new Error(`unknown kpop group slug ${q.group_slug}`);
    const sources = [...new Set([...(q.sources ?? []), ...q.questions.map((x) => x.source)])];
    const notes = `Sources: ${sources.join(' ; ')}. ${review}`;
    const questions = JSON.stringify(q.questions);
    return `  (${sqlText(q.title)}, ${sqlText(q.description)}, ${gid ?? 'null'}, ${sqlText(q.quiz_type)}, ${sqlText(q.difficulty)}, ${sqlText(q.category)}, ${sqlText(questions)}::jsonb, ${sqlText(q.scheduled_date)}::date, 'verified', now(), ${sqlText(notes)})`;
  });

  const first = lot[0]!.scheduled_date;
  const last = lot.at(-1)!.scheduled_date;
  // Lot 1 kept its October name; a lot is named after the month of its first date.
  const base = `daily-bank-${lotN === '1' ? '2026-10' : first.slice(0, 7)}-lot${lotN}`;
  const titles = lot.map((q) => sqlText(q.title)).join(', ');
  const kpop = kpopRowSql('qb');
  const lotRows = `public.quiz_bank qb where qb.title in (${titles}) and qb.scheduled_date between ${sqlText(first)} and ${sqlText(last)} and ${kpop}`;
  const n = lot.length;
  const placeholders = review.includes('{');
  const header = `-- Daily quiz bank, lot ${lotN}: ${n} quizzes for ${first} to ${last} (Mission U, owner 2026-10-15).
-- Generated by apps/quiz/scripts/daily-bank/to-sql.mts (apps/quiz/src/lib/daily-bank/lot-sql.ts); proved on PGlite by lot-sql.test.ts.
-- Rollback: ${base}-rollback.sql (removes only rows of this lot not yet published).
-- ONE do block, no temp table: safe to paste in the Supabase SQL Editor. Atomic: any failed check below undoes everything.
-- Before the code? YES. It is data the current code already reads (the daily rotation pulls verified rows by date).
-- KPOP ONLY: these rows are for kpopquiz.org. The insert names no site_id: before Run O1's 002a every row is a kpop row,
-- after it the column default 'kpop' fills it. The checks stop the block if a row of this lot is on another site, and the
-- date check reads kpop rows only. A second run raises (two rows on one date) and changes nothing.
${placeholders ? '-- REVIEW NOT RECORDED: replace {REVIEWER} and {REVIEW_DATE} below after the review; until then the block refuses to apply.\n' : ''}-- Verify (read-only, run after the apply; the status line holds until the first row of the lot is published on ${first}):
-- Verify: select count(*) from ${lotRows} and qb.status = 'verified' and qb.published_quiz_id is null;   expect ${n}
-- Verify: select count(distinct qb.scheduled_date) from ${lotRows};   expect ${n}
-- Verify: select min(qb.scheduled_date)::text || ' ' || max(qb.scheduled_date)::text from ${lotRows};   expect ${first} ${last}
-- Verify: select count(*) from public.quiz_bank qb where qb.scheduled_date between ${sqlText(first)} and ${sqlText(last)} and qb.status in ('verified', 'scheduled') and ${kpop};   expect ${n}
`;
  const pin = lotN === '1' ? `
  -- The rotation (lib/ux-v1/p1/qotd-rotation.ts, pickBankEntryForDate) fills a day with no row of
  -- its own by pulling, in order: overdue rows, rows with no date, then future rows by date. Left
  -- dated 2029 and later, the old open rows would be pulled AFTER this lot's rows and shift every
  -- date of the lot. Without a date they are pulled first, and the lot keeps its dates.
  update public.quiz_bank qb set scheduled_date = null, updated_at = now()
  where status in ('verified', 'scheduled') and scheduled_date >= '2029-01-01' and ${kpop};
` : '';
  const sql = `${header}
do $lot$
declare
  inserted integer;
begin
  perform set_config('lock_timeout', '5s', true);
${pin}
  insert into public.quiz_bank (title, description, group_id, quiz_type, difficulty, category, questions, scheduled_date, status, verified_at, verification_notes)
  values
${values.join(',\n')};
  get diagnostics inserted = row_count;
  if inserted <> ${n} then
    raise exception 'daily bank lot ${lotN}: % rows inserted instead of ${n}, nothing applied', inserted;
  end if;

  -- Check: every row this block just inserted (verified_at = now(), the start of the transaction) is a
  -- kpop row (no site_id column yet, or site_id 'kpop'). If not, nothing is applied.
  if exists (
    select 1 from public.quiz_bank qb
    where qb.verified_at = now() and qb.title in (${titles}) and not (${kpop})
  ) then
    raise exception 'daily bank lot ${lotN}: a row of this lot is not a kpop row, nothing applied';
  end if;
${placeholders ? `
  -- Check: the review is recorded. While {REVIEWER} or {REVIEW_DATE} is still in the notes, nothing is applied.
  if exists (select 1 from public.quiz_bank qb where qb.verified_at = now() and qb.verification_notes ~ '[{](REVIEWER|REVIEW_DATE)[}]') then
    raise exception 'daily bank lot ${lotN}: review not recorded (replace {REVIEWER} and {REVIEW_DATE}), nothing applied';
  end if;
` : ''}
  -- Check: one kpop row per date, no clash with a row already scheduled on these dates (a second run stops here).
  if exists (
    select 1 from public.quiz_bank qb
    where qb.scheduled_date between ${sqlText(first)} and ${sqlText(last)} and qb.status in ('verified', 'scheduled') and ${kpop}
    group by qb.scheduled_date having count(*) > 1
  ) then
    raise exception 'daily bank lot ${lotN}: two rows on one date, nothing applied';
  end if;
end $lot$;
`;
  const rbRows = `public.quiz_bank qb where qb.title in (${titles}) and qb.status in ('verified', 'scheduled') and qb.published_quiz_id is null and ${kpop}`;
  const rollback = `-- Rollback of ${base}.sql: removes the rows of this lot that were not
-- published yet (a published row is already a live quiz page; it stays). Kpop rows only.
-- ONE do block, no temp table. Idempotent.
-- Verify (read-only, run after the rollback):
-- Verify: select count(*) from ${rbRows};   expect 0
-- Verify: select count(*) from public.quiz_bank qb where qb.scheduled_date between ${sqlText(first)} and ${sqlText(last)} and qb.status in ('verified', 'scheduled') and qb.title in (${titles}) and ${kpop};   expect 0

do $lot$
begin
  perform set_config('lock_timeout', '5s', true);
  delete from public.quiz_bank qb
  where title in (${titles}) and status in ('verified', 'scheduled') and published_quiz_id is null and ${kpop};
end $lot$;
`;
  return { name: `${base}.sql`, rollbackName: `${base}-rollback.sql`, sql, rollback };
}
