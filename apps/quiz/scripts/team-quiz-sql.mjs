// The SQL of a Team quiz draft (SEO Mission 2 part B point 8), shared by
// scripts/build-team-quiz-sql.mjs (writes the files) and the unit test that checks them.
// Pure: content in, two strings out.

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const SLUG = /^[a-z0-9-]{1,80}$/;

/** A SQL string literal (single quotes doubled). */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** A jsonb literal in a dollar-quoted string whose tag cannot occur in the JSON. */
function jsonb(value) {
  const text = JSON.stringify(value, null, 2);
  let tag = 'json';
  while (text.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${text}$${tag}$::jsonb`;
}

/** The rows the database stores: the question, its options, the answer and the fun fact (no sources). */
export function storedQuestions(content) {
  return content.questions.map((q) => ({ question: q.question, options: q.options, correct: q.correct, fun_fact: q.fun_fact }));
}

export function buildTeamQuizSql(content) {
  const { slug, title, groupSlug, creatorId, quizType, difficulty, language, settings } = content;
  if (!SLUG.test(slug) || !SLUG.test(groupSlug)) throw new Error('bad slug');
  if (!UUID.test(creatorId)) throw new Error('bad creator id');
  const questions = storedQuestions(content);

  const up = `-- SEO Mission 2, part B point 8: the Team quiz "${title}" (/q/${slug}), as a DRAFT.
-- Generated by apps/quiz/scripts/build-team-quiz-sql.mjs from
-- apps/quiz/src/data/team-quizzes/${slug}.json (questions, answers, fun facts and the sources
-- each answer was checked against). Do not edit by hand: edit the JSON and re-run the script.
--
-- What it does, in one transaction:
--   1. refuses to run if the slug already exists or the Team profile is missing;
--   2. inserts the quiz with status 'draft', owned by the KpopQuizz Team profile
--      (${creatorId}), in the ${groupSlug} group. A draft is not public: /q/${slug}
--      answers 404, and it is in no list, sitemap or count of published quizzes;
--   3. the insert trigger handle_new_quiz() adds 1 to groups.quiz_count and to the Team's
--      profiles.total_quizzes_created (as for every quiz) and writes a 'quiz_created' activity
--      event; that event is deleted here, so the feed never points at an unpublished quiz.
--      No alert is sent: the alert triggers fire only on 'published'.
--
-- The level result: settings.result_levels (read by apps/quiz/src/lib/quiz/result-levels.ts).
-- The results screen names the level reached; "You beat N% of players" shows only from 200
-- finished attempts. A quiz without result_levels is unchanged.
--
-- Run: Supabase SQL editor, the whole file. Rollback: seo-m2-${slug}-rollback.sql.
--
-- PUBLISH, only with the owner's go, after reading the draft (this fires the group's
-- "new quiz" alerts once, like any publish):
--   update public.quizzes set status = 'published', updated_at = now()
--   where slug = ${lit(slug)} and status = 'draft';

begin;

do $guard$
begin
  if exists (select 1 from public.quizzes where slug = ${lit(slug)}) then
    raise exception 'quiz % already exists', ${lit(slug)};
  end if;
  if not exists (select 1 from public.profiles where id = ${lit(creatorId)}::uuid) then
    raise exception 'Team profile % is missing', ${lit(creatorId)};
  end if;
  if not exists (select 1 from public.groups where slug = ${lit(groupSlug)}) then
    raise exception 'group % is missing', ${lit(groupSlug)};
  end if;
end
$guard$;

insert into public.quizzes (creator_id, group_id, title, slug, quiz_type, questions, settings, difficulty, status, question_count, language)
select
  ${lit(creatorId)}::uuid,
  g.id,
  ${lit(title)},
  ${lit(slug)},
  ${lit(quizType)},
  ${jsonb(questions)},
  ${jsonb(settings)},
  ${lit(difficulty)},
  'draft',
  ${questions.length},
  ${lit(language)}
from public.groups g
where g.slug = ${lit(groupSlug)};

-- The 'quiz_created' event the insert trigger just wrote (same transaction, so now() is the
-- same instant as its created_at default).
delete from public.activity_events
where event_type = 'quiz_created'
  and user_id = ${lit(creatorId)}::uuid
  and payload ->> 'title' = ${lit(title)}
  and created_at = now();

commit;
`;

  const down = `-- Rollback of seo-m2-${slug}.sql (generated by apps/quiz/scripts/build-team-quiz-sql.mjs).
-- Removes the Team quiz "${title}" while it is still a DRAFT, and gives back the two counters
-- its insert added (groups.quiz_count, the Team's profiles.total_quizzes_created). It refuses
-- to touch a published quiz: once published, it has plays and links, and removing it is a
-- product decision (status 'removed' through the admin tools), not a rollback.

begin;

do $guard$
begin
  if exists (select 1 from public.quizzes where slug = ${lit(slug)} and status <> 'draft') then
    raise exception 'quiz % is no longer a draft: not rolled back', ${lit(slug)};
  end if;
end
$guard$;

with gone as (
  delete from public.quizzes
  where slug = ${lit(slug)} and status = 'draft' and creator_id = ${lit(creatorId)}::uuid
  returning group_id, creator_id
),
g as (
  update public.groups set quiz_count = greatest(quiz_count - 1, 0)
  where id in (select group_id from gone)
  returning id
)
update public.profiles set total_quizzes_created = greatest(total_quizzes_created - 1, 0), updated_at = now()
where id in (select creator_id from gone);

commit;
`;
  return { up, down };
}
