#!/usr/bin/env node
// KpopCards, PR #231: writes the three ALL files of docs/pending-migrations/cards from the 15 files, so the owner runs ONE script:
//   ALL-099-115.sql  begin; a guard; the 15 files verbatim in the closed order; commit;  (one transaction, all or nothing)
//   ALL-verify.sql   one read-only SELECT: a row per `-- Verify:` line of the 15 files, then TOUT_OK (bundle-verify.mjs)
//   ALL-rollback.sql begin; the 15 rollbacks verbatim from 115 down to 099; 101-catalog.sql again; commit;
// Usage: node apps/quiz/scripts/cards/bundle-sql.mjs          rewrites the three files
//        node apps/quiz/scripts/cards/bundle-sql.mjs --check  writes nothing, exits 1 when a committed file differs
// The 15 files are never changed here; bundle-sql.test.ts checks the committed ALL files against this script.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildVerify } from './bundle-verify.mjs';

export const CARDS_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../../docs/pending-migrations/cards');

/** The 15 files, in the order the integrator closed on 2026-11-14 (099b is a companion of 099 that runs after 102). */
export const ORDER = [
  '099-idols-members', '102-catalog-rebuild', '099b-idols-returning', '103-catalog-photos', '104-economy', '105-goals', '106-demo',
  '107-prefs', '108-push', '110-core', '111-group-types', '112-social', '113-moment', '114-catalog-append', '115-quiz-of-day-bonus',
];

export const OUTPUTS = { bundle: 'ALL-099-115.sql', verify: 'ALL-verify.sql', rollback: 'ALL-rollback.sql' };

export const readCards = (name) => readFileSync(path.join(CARDS_DIR, name), 'utf8');

/** The guard of the bundle: refuses, with nothing changed, outside the state the integrator read in production on 2026-11-14.
 *  now() appears once: the tests replace it to try the time window. */
export const GUARD = `do $all_guard$
declare
  v_utc time := (now() at time zone 'UTC')::time;
begin
  -- The quiz of the day and the Paris day turn around midnight: never between 23:50 and 00:30 UTC.
  if v_utc >= time '23:50' or v_utc < time '00:30' then
    raise exception 'ALL-099-115: refused between 23:50 and 00:30 UTC (it is % UTC now), nothing changed; run it after 00:30 UTC', to_char(v_utc, 'HH24:MI');
  end if;
  if to_regclass('public.cards_catalog') is null or to_regclass('public.cards_owned') is null or to_regclass('public.cards_packs') is null then
    raise exception 'ALL-099-115: public.cards_catalog is missing (001 to 003 and 101 are not applied), nothing changed';
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'cards_catalog' and column_name = 'part') then
    raise exception 'ALL-099-115: cards_catalog already has the column part (102 is applied), nothing changed; the bundle runs once, on the state of 2026-11-14';
  end if;
  if exists (select 1 from public.cards_owned) then
    raise exception 'ALL-099-115: a player owns a card (cards_owned is not empty), nothing changed';
  end if;
  if exists (select 1 from public.cards_packs) then
    raise exception 'ALL-099-115: a pack was opened (cards_packs is not empty), nothing changed';
  end if;
  raise notice 'ALL-099-115: guard passed at % UTC (no part column, no card owned, no pack opened)', to_char(v_utc, 'HH24:MI');
end $all_guard$;
`;

const sep = (i, n, name, note = 'verbatim') => `-- ==== ${i}/${n}: ${name} (${note}) ====\n`;
const withNl = (s) => (s.endsWith('\n') ? s : `${s}\n`);

export function buildBundle(read = readCards) {
  const header = [
    '-- ALL-099-115.sql: the 15 KpopCards SQL files of PR #231 in ONE transaction (generated by apps/quiz/scripts/cards/bundle-sql.mjs, do not edit)',
    '--',
    '-- What:   begin; a guard; the 15 files of docs/pending-migrations/cards verbatim, in this order:',
    `--         ${ORDER.slice(0, 8).join(', ')},`,
    `--         ${ORDER.slice(8).join(', ')}; commit;`,
    '--         All or nothing: an error anywhere (the guard, a file, a refusal of a file) leaves the database as it was.',
    '-- Guard:  refuses, nothing changed, between 23:50 and 00:30 UTC; when public.cards_catalog is missing (001 to 003 and 101 not applied);',
    '--         when cards_catalog already has the column part (102 applied); when cards_owned or cards_packs has a row.',
    '-- How:    after a backup. Supabase SQL Editor: paste the whole file and Run (the editor sends it as one query). Or psql, with the',
    '--         connection in SUPABASE_DB_URL (no password in the command):',
    '--           psql "$SUPABASE_DB_URL" -X -v ON_ERROR_STOP=1 -f docs/pending-migrations/cards/ALL-099-115.sql',
    '--         Do not add -1 / --single-transaction: the file has its own begin and commit.',
    '-- Then:   ALL-verify.sql (read only, one row per Verify line, the last row TOUT_OK must be true). Undo: ALL-rollback.sql.',
    '',
  ].join('\n');
  const parts = ORDER.map((f, i) => sep(i + 1, ORDER.length, `${f}.sql`) + withNl(read(`${f}.sql`)));
  return `${header}begin;\n\n${GUARD}\n${parts.join('\n')}\ncommit;\n`;
}

/** The rollbacks undo the bundle; 103's and 102's empty the catalog, so 101 (applied before the bundle) runs again at the end. */
export function buildRollback(read = readCards) {
  const rev = [...ORDER].reverse();
  const header = [
    '-- ALL-rollback.sql: undoes ALL-099-115.sql in ONE transaction (generated by apps/quiz/scripts/cards/bundle-sql.mjs, do not edit)',
    '--',
    '-- What:   begin; the 15 rollback files verbatim, from 115 down to 099:',
    `--         ${rev.slice(0, 8).map((f) => `${f}.rollback`).join(', ')},`,
    `--         ${rev.slice(8).map((f) => `${f}.rollback`).join(', ')};`,
    '--         then 101-catalog.sql verbatim; commit;',
    '-- Why 101: 103 and 102 replace the catalog of 101, and their rollbacks empty it (they cannot know the rows they replaced). 101 was',
    '--         applied before the bundle; run again on the restored groups and idols it writes the same subjects, cards and photos.',
    '--         The photo ids are new (cards_photos.id is an identity, its sequence does not go back), and so is cards_catalog.photo_id.',
    '-- Refuses: what each rollback refuses (a card owned, a pack opened, a craft, a claim, an idempotency row, a lock...): then nothing',
    '--         changes. Run it only after ALL-099-115.sql.',
    '-- How:    Supabase SQL Editor: paste the whole file and Run. Or:',
    '--           psql "$SUPABASE_DB_URL" -X -v ON_ERROR_STOP=1 -f docs/pending-migrations/cards/ALL-rollback.sql',
    '-- Then:   ALL-verify.sql answers TOUT_OK false (the bundle is undone).',
    '',
  ].join('\n');
  const n = rev.length + 1;
  const parts = rev.map((f, i) => sep(i + 1, n, `${f}.rollback.sql`) + withNl(read(`${f}.rollback.sql`)));
  parts.push(sep(n, n, '101-catalog.sql', 'verbatim, the catalog of before the bundle') + withNl(read('101-catalog.sql')));
  return `${header}begin;\n\n${parts.join('\n')}\ncommit;\n`;
}

export function buildAll(read = readCards) {
  return {
    [OUTPUTS.bundle]: buildBundle(read),
    [OUTPUTS.verify]: buildVerify(read, ORDER),
    [OUTPUTS.rollback]: buildRollback(read),
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  const out = buildAll();
  let stale = 0;
  for (const [name, text] of Object.entries(out)) {
    if (/[\u2013\u2014]/.test(text)) throw new Error(`${name}: an en or em dash`);
    const file = path.join(CARDS_DIR, name);
    let now = null;
    try { now = readFileSync(file, 'utf8'); } catch { /* not written yet */ }
    if (now === text) { console.log(`${name}: up to date (${Buffer.byteLength(text)} bytes)`); continue; }
    if (check) { console.log(`${name}: differs from the generator`); stale++; continue; }
    writeFileSync(file, text);
    console.log(`${name}: written (${Buffer.byteLength(text)} bytes)`);
  }
  if (stale) process.exit(1);
}
