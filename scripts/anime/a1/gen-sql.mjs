// gen-sql.mjs (lot A1): writes L13-A1-character-facts.sql and its rollback from data/a1-facts.json. No network, no secret, no database.
//   node scripts/anime/a1/gen-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '../../..')
const OUT = join(ROOT, 'docs/pending-migrations/multisite/launch')
const { characters, series } = JSON.parse(readFileSync(join(HERE, 'data/a1-facts.json'), 'utf8'))

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const list = (xs) => xs.map(q).join(', ')
const FIELDS = ['gender', 'species', 'role_at_debut', 'first_appearance', 'voice_actor_ja']
const slugs = series.map((s) => s.slug).sort()
const inSeries = `g.site_id = 'anime' and g.slug in (${list(slugs)})`
const charId = (s, c) => `(select c.id from public.characters c join public.groups g on g.id = c.group_id where g.site_id = 'anime' and g.slug = ${q(s)} and c.slug = ${q(c)})`
const pairs = characters.map((c) => `(${q(c.series)}, ${q(c.slug)})`).join(', ')
const source = (type, id, field, v) => `insert into public.entity_sources (entity_type, entity_id, field, source, source_ref, source_url, fetched_at) values (${q(type)}, ${q(id)}, ${q(field)}, ${q(v.source)}, ${q(v.source_ref)}, ${q(v.source_url)}, ${q(v.fetched_at)}::timestamptz) on conflict (entity_type, entity_id, field, source) do update set source_ref = excluded.source_ref, source_url = excluded.source_url, fetched_at = excluded.fetched_at where (entity_sources.source_ref, entity_sources.source_url, entity_sources.fetched_at) is distinct from (excluded.source_ref, excluded.source_url, excluded.fetched_at);`

const nValues = characters.reduce((n, c) => n + Object.keys(c.values).length, 0)
const complete = characters.filter((c) => ['gender', 'species', 'role_at_debut'].every((f) => c.values[f])).length
const lines = []
lines.push(`-- L13-A1-character-facts.sql (lot A1, 2026-10-30; generated by scripts/anime/a1/gen-sql.mjs, do not edit by hand)`)
lines.push(`--`)
lines.push(`-- What:   the Otakudle facts of docs/o1/contracts/dle-a1-characters.md: ${series.length} series_facts rows (demographic), ${characters.length} character_facts rows (${complete} with gender, species and role_at_debut), and ${series.length + nValues} entity_sources rows, one per stored value. Upserts only. It touches no other table, no row of L01 to L12, no kpop row.`)
lines.push(`-- Owner:  applies the owner's answers to the A1 review. Species of Goku (saiyan), Nezuko (demon) and Denji (hybrid) depart from the contract's "species shown first" by the owner's decision. Hunter x Hunter voices are the 2011 series (Madhouse), like the studio in L04.`)
lines.push(`-- Needs:  L04 (series and characters), 011 (entity_sources.source_url and widened checks), 023 (the two tables).`)
lines.push(`-- Verify: docs/launch/o1/checks/V-L13.sql (session.sh J4); select count(*) from public.series_facts;   expect ${series.length}`)
lines.push(`--         select count(*) from public.character_facts;   expect ${characters.length}`)
lines.push(`-- Undo:   L13-A1-character-facts.rollback.sql (refused once the game otakudle has a play).`)
lines.push(`-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing.`)
lines.push(``)
lines.push(`set lock_timeout = '5s';`)
lines.push(`set client_min_messages = warning;`)
lines.push(`do $a1$ begin`)
lines.push(`  if to_regclass('public.character_facts') is null or to_regclass('public.series_facts') is null then`)
lines.push(`    raise exception 'L13: public.character_facts or public.series_facts is missing (apply 023 first)';`)
lines.push(`  end if;`)
lines.push(`  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'entity_sources' and column_name = 'source_url') then`)
lines.push(`    raise exception 'L13: entity_sources.source_url is missing (apply 011 first)';`)
lines.push(`  end if;`)
lines.push(`  if (select count(*) from public.groups g where ${inSeries}) <> ${series.length} then`)
lines.push(`    raise exception 'L13: the series groups are missing (apply L04 first)';`)
lines.push(`  end if;`)
lines.push(`  if (select count(*) from public.characters c join public.groups g on g.id = c.group_id where g.site_id = 'anime' and (g.slug, c.slug) in (${pairs}) and c.status = 'published' and c.spoiler_level = 0 and not c.identity_spoiler) <> ${characters.length} then`)
lines.push(`    raise exception 'L13: a character of this file is missing or out of the pool (draft or spoiler) in L04';`)
lines.push(`  end if;`)
lines.push(`end $a1$;`)
lines.push(``)
lines.push(`-- series_facts: the demographic of the original work, the 50 launch series.`)
for (const s of series) {
  lines.push(`insert into public.series_facts (group_id, demographic) values ((select g.id from public.groups g where g.site_id = 'anime' and g.slug = ${q(s.slug)}), ${q(s.demographic.value)}) on conflict (group_id) do update set demographic = excluded.demographic, updated_at = now() where series_facts.demographic is distinct from excluded.demographic;`)
  lines.push(source('series', s.slug, 'demographic', s.demographic))
}
lines.push(``)
lines.push(`-- character_facts: as the reader first meets the character. Null: not known for sure, so not a target.`)
for (const c of characters) {
  const v = (f) => q(c.values[f]?.value)
  lines.push(`insert into public.character_facts (character_id, ${FIELDS.join(', ')}) values (${charId(c.series, c.slug)}, ${FIELDS.map(v).join(', ')}) on conflict (character_id) do update set ${FIELDS.map((f) => `${f} = excluded.${f}`).join(', ')}, updated_at = now() where (${FIELDS.map((f) => `character_facts.${f}`).join(', ')}) is distinct from (${FIELDS.map((f) => `excluded.${f}`).join(', ')});`)
  for (const f of FIELDS) if (c.values[f]) lines.push(source('character', c.slug, f, c.values[f]))
}
writeFileSync(join(OUT, 'L13-A1-character-facts.sql'), `${lines.join('\n')}\n`)

const back = []
back.push(`-- L13-A1-character-facts.rollback.sql (lot A1, 2026-10-30; generated by scripts/anime/a1/gen-sql.mjs, do not edit by hand)`)
back.push(`--`)
back.push(`-- What:   undoes L13: deletes the rows of the 50 launch series from character_facts and series_facts, and their entity_sources rows of the six fields. Refused once the game otakudle has a play.`)
back.push(`-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing.`)
back.push(``)
back.push(`set lock_timeout = '5s';`)
back.push(`set client_min_messages = warning;`)
back.push(`do $a1$`)
back.push(`declare plays bigint := 0;`)
back.push(`begin`)
back.push(`  if to_regclass('public.dle_plays') is not null then`)
back.push(`    execute $q$select count(*) from public.dle_plays where game_id = 'otakudle'$q$ into plays;`)
back.push(`  end if;`)
back.push(`  if plays > 0 then`)
back.push(`    raise exception 'L13 rollback refused: the game otakudle has a play';`)
back.push(`  end if;`)
back.push(`end $a1$;`)
back.push(``)
back.push(`delete from public.character_facts where character_id in (select c.id from public.characters c join public.groups g on g.id = c.group_id where ${inSeries});`)
back.push(`delete from public.series_facts where group_id in (select g.id from public.groups g where ${inSeries});`)
back.push(`delete from public.entity_sources where entity_type = 'character' and field in (${list(FIELDS)}) and entity_id in (select c.slug from public.characters c join public.groups g on g.id = c.group_id where ${inSeries});`)
back.push(`delete from public.entity_sources where entity_type = 'series' and field = 'demographic' and entity_id in (${list(slugs)});`)
writeFileSync(join(OUT, 'L13-A1-character-facts.rollback.sql'), `${back.join('\n')}\n`)
console.log(`L13: ${series.length} series, ${characters.length} characters, ${complete} complete, ${series.length + nValues} sources`)
