// Lane opaff: generates docs/anime/data/dle/one-piece-affiliation.json, launch/L17-l1-op-affiliation.sql and its rollback.
// Run: node scripts/anime/opaff/gen-l17.mjs   (no dependency; reads scripts/anime/a2/data/one-piece.json and launch/L15-A2-series-games.sql)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { D, FAMILY, WAS, FLAGS } from './decisions.mjs';
import { toSingleDoBlock } from '../sql/single-do-block.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const LAUNCH = path.join(ROOT, 'docs/pending-migrations/multisite/launch');
const data = JSON.parse(readFileSync(path.join(ROOT, 'scripts/anime/a2/data/one-piece.json'), 'utf8'));
const l15 = readFileSync(path.join(LAUNCH, 'L15-A2-series-games.sql'), 'utf8').split('\n');
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

// Original affiliation subtree of each character, byte for byte from L15.
const orig = new Map();
const arcs = new Map();
for (const l of l15) {
  if (!l.startsWith('insert into public.character_game_facts') || !l.includes("'otakudle-one-piece'")) continue;
  const slug = /c\.slug = '([^']+)'\)/.exec(l)[1];
  const attrs = /'(\{"gender".*?\})'::jsonb/.exec(l)[1];
  const m = /"affiliation":(\{.*?\}),"devil_fruit_type"/.exec(attrs);
  orig.set(slug, m[1].replace(/''/g, "'"));
  arcs.set(slug, /"debut_arc":\{"v":\d+,"l":"([^"]*)"/.exec(attrs)[1]);
}
const chars = data.characters;
if (orig.size !== 100 || chars.length !== 100) throw new Error('expected 100 characters');
const out = [];
const rows = [];
const srcRows = [];
for (const c of chars) {
  const d = D[c.slug];
  if (!d) throw new Error('no decision for ' + c.slug);
  const [aff, fam, note] = d;
  const fam2 = FAMILY[fam];
  out.push({ slug: c.slug, name: c.name, affiliation: aff, family: aff ? fam2 : null, source: aff ? c.ids.fandom_url : null, note });
  if (!aff) continue;
  const v = fam2 ? { v: aff, p: [fam2] } : { v: aff };
  rows.push({ slug: c.slug, v: JSON.stringify(v), old: orig.get(c.slug) });
  if (orig.get(c.slug) === '{"v":null}') srcRows.push({ slug: c.slug, rev: c.ids.fandom_revision, url: c.ids.fandom_url });
}
mkdirSync(path.join(ROOT, 'docs/anime/data/dle'), { recursive: true });
writeFileSync(path.join(ROOT, 'docs/anime/data/dle/one-piece-affiliation.json'), JSON.stringify(out, null, 2) + '\n');

// Rule A (owner 2026-11-09): the list of the characters whose value differs from PR #215, and the full list for the owner.
const rowOf = (x) => {
  const was = WAS[x.slug];
  const wasAff = was ? was[0] : x.affiliation;
  const wasFam = was ? FAMILY[was[1]] : x.family;
  return { slug: x.slug, name: x.name, debut_arc: arcs.get(x.slug), in_215: wasAff, rule_a: x.affiliation, family: x.family, source: x.source, changed: !!was, flag: FLAGS[x.slug] ?? '', note: x.note, was_family: wasFam };
};
const all = out.map(rowOf);
for (const k of Object.keys(WAS)) if (!out.find((x) => x.slug === k)) throw new Error('unknown slug ' + k);
const diffs = all.filter((r) => r.changed).map(({ slug, name, debut_arc, in_215, rule_a, family, source, flag }) => ({ slug, name, debut_arc, in_215, rule_a, family, source, reasoning: flag }));
writeFileSync(path.join(ROOT, 'docs/anime/data/dle/one-piece-affiliation-rule-diffs.json'), JSON.stringify({ rule: 'A: the group at the end of the debut arc, as the reader knows it then', diffs }, null, 2) + '\n');
{
  const esc = (v) => String(v ?? '').replace(/\|/g, '/');
  const line = (r) => `| ${esc(r.name)} | ${esc(r.debut_arc)} | ${esc(r.in_215 ?? '(empty)')} | ${esc(r.rule_a ?? '(empty)')} | ${esc(r.family ?? 'none')} | ${esc(r.source)} | ${r.flag ? '⚑ ' + esc(r.flag) : ''} |`;
  const head = '| Character | Debut arc | Value in #215 | Rule A value | Family | Source | Flag |\n|---|---|---|---|---|---|---|';
  const ch = all.filter((r) => r.changed);
  const un = all.filter((r) => !r.changed);
  const md = `# One Piece affiliation under rule A (lane magazine, round 3, 2026-11-09)

Rule A (owner): the group the character belongs to at the END of their debut arc (the game's "Debut arc" column), as the reader knows it then.
Generated by scripts/anime/opaff/gen-l17.mjs from scripts/anime/opaff/decisions.mjs; source of each row: the Fandom infobox captured in scripts/anime/a2/data/one-piece.json (revision ids inside).

Counts: ${ch.length} changed, ${un.length} unchanged, ${all.filter((r) => r.flag).length} with a reasoning sentence (the audit's flagged rows, the rows that differ from the audit, and the changed rows).

## Changed (${ch.length})

${head}
${ch.map(line).join('\n')}

## Unchanged (${un.length})

${head}
${un.map(line).join('\n')}
`;
  mkdirSync(path.join(ROOT, 'docs/o1/reports/L1'), { recursive: true });
  writeFileSync(path.join(ROOT, 'docs/o1/reports/L1/op-affiliation-rule-a.md'), md);
}

const affs = new Set(out.filter((x) => x.affiliation).map((x) => x.affiliation));
const fams = new Set(out.filter((x) => x.family).map((x) => x.family));
const judg = out.filter((x) => x.note.startsWith('Judgement') || x.note.startsWith('UNSOURCED')).length;
const noFam = out.filter((x) => x.affiliation && !x.family).length;
const stats = `${out.length} characters, ${out.filter((x) => x.affiliation).length} with a main affiliation, ${affs.size} affiliations, ${fams.size} families (${[...fams].join(', ')}), ${noFam} with no family, ${judg} judgement calls, ${out.filter((x) => !x.affiliation).length} unsourced`;

const slugList = rows.map((r) => `(${q(r.slug)}, ${q(r.v)}::jsonb)`).join(',\n    ');
const oldList = rows.map((r) => `(${q(r.slug)}, ${q(r.old)}::jsonb)`).join(',\n    ');
const srcList = srcRows.map((r) => `(${q(r.slug)}, ${q(r.rev)}, ${q(r.url)})`).join(',\n    ');
const slugsIn = (arr) => arr.map((r) => q(r.slug)).join(', ');

const sql = `-- L17-l1-op-affiliation.sql (lane opaff then lane magazine, run O1, owner 2026-11-08 and rule A of 2026-11-09; generated by scripts/anime/opaff/gen-l17.mjs, do not edit by hand)
--
-- SUPERSEDES the L17 of PR #215: same file name, rule A of the owner (the group at the END of the debut arc, as the reader knows it then). Re-runnable: it sets each value by slug,
--         so applying it on top of the #215 version (already applied or not) is enough; only the rows rule A changes move (see docs/o1/reports/L1/op-affiliation-rule-a.md).
--
-- What:   Otakudle One Piece, column affiliation: from multi (several crews, "one in common is near") to single, ONE main affiliation per character
--         ({"v": affiliation, "p": [family]}, dle_compare: same v is Right, same family p is Near, else Wrong; no "p" means no Near).
--         Families: pirates (every crew, Yonko and subordinate crews, Cross Guild), marines, world-government (Cipher Pol, Impel Down, the World Government),
--         revolutionary-army; kingdoms, clans, Minks and civilians have no family. ${stats}.
--         Sources: data in docs/anime/data/dle/one-piece-affiliation.json (the Fandom infobox of each character, captured in scripts/anime/a2/data/one-piece.json).
--         Updates the attrs.affiliation of ${rows.length} character_game_facts rows (otakudle-one-piece), the kind of the column in dle_attributes, and adds ${srcRows.length} entity_sources
--         rows (fandom) for characters that had no value (${srcRows.map((r) => r.slug).join(', ')}). can_be_target is not touched.
--         Nothing else: no other column, no Dragon Ball row, no kpop row.
-- Needs:  019, 024, L04, L15.
-- WHEN:   apply at a day boundary, after 00:30 UTC and never between 23:50 and 00:30 UTC, after a backup. A guess is stored as the entity id only (dle_plays.guesses) and its
--         colours are computed on every read (dle_play_state -> dle_compare_all) from the live column kind and from the dle_entities snapshot: applying mid-day makes the
--         kind change at once (a guess shown "near" on a shared crew can turn "wrong" for a play in progress) and the values change at the next dle_refresh_entities
--         (this file calls it for the game when it already has a snapshot, so the change is immediate and consistent). Past days' colours are recomputed the same way.
-- Undo:   L17-l1-op-affiliation.rollback.sql (restores the attrs.affiliation of L15 byte for byte and the kind multi).
-- o1-transaction: single (psql --single-transaction). Idempotent: a second run changes nothing.

set lock_timeout = '5s';
set client_min_messages = warning;
do $op$ begin
  if to_regclass('public.character_game_facts') is null or to_regclass('public.dle_attributes') is null then
    raise exception 'L17: 019 and 024 must be applied first';
  end if;
  if (select count(*) from public.character_game_facts where game_id = 'otakudle-one-piece') < 100 then
    raise exception 'L17: the 100 One Piece facts of L15 are not all there (apply L15 first)';
  end if;
end $op$;

update public.dle_attributes set kind = 'single' where game_id = 'otakudle-one-piece' and key = 'affiliation' and kind <> 'single';

with n(slug, val) as (values
    ${slugList}
)
update public.character_game_facts f
set attrs = jsonb_set(f.attrs, '{affiliation}', n.val), updated_at = now()
from n
join public.characters c on true
join public.groups g on g.id = c.group_id and g.site_id = 'anime' and g.slug = 'one-piece' and c.slug = n.slug
where f.character_id = c.id and f.game_id = 'otakudle-one-piece' and f.attrs -> 'affiliation' is distinct from n.val;

with s(slug, rev, url) as (values
    ${srcList}
)
insert into public.entity_sources (entity_type, entity_id, field, source, source_ref, source_url, fetched_at)
select 'character', s.slug, 'one-piece.affiliation', 'fandom', s.rev, s.url, '2026-11-02T00:00:00Z'::timestamptz from s
on conflict (entity_type, entity_id, field, source) do nothing;

-- The snapshot the players read (dle_entities): refreshed now when the game already has one, otherwise the next activation takes it.
do $op$ begin
  if exists (select 1 from public.dle_entities where game_id = 'otakudle-one-piece') then
    perform public.dle_refresh_entities('otakudle-one-piece');
  end if;
end $op$;
`;
const rb = `-- L17-l1-op-affiliation.rollback.sql (lane opaff, run O1; generated by scripts/anime/opaff/gen-l17.mjs from the data of L15, do not edit by hand)
--
-- What:   undoes L17: the attrs.affiliation of the ${rows.length} characters back to the value of L15 byte for byte, the column kind back to multi, and removes the ${srcRows.length} entity_sources rows L17 added.
--         Apply at a day boundary like L17 (same remark on guesses). Idempotent.
-- o1-transaction: single (psql --single-transaction).

set lock_timeout = '5s';
set client_min_messages = warning;

update public.dle_attributes set kind = 'multi' where game_id = 'otakudle-one-piece' and key = 'affiliation' and kind <> 'multi';

with n(slug, val) as (values
    ${oldList}
)
update public.character_game_facts f
set attrs = jsonb_set(f.attrs, '{affiliation}', n.val), updated_at = now()
from n
join public.characters c on true
join public.groups g on g.id = c.group_id and g.site_id = 'anime' and g.slug = 'one-piece' and c.slug = n.slug
where f.character_id = c.id and f.game_id = 'otakudle-one-piece' and f.attrs -> 'affiliation' is distinct from n.val;

delete from public.entity_sources where entity_type = 'character' and field = 'one-piece.affiliation' and source = 'fandom' and entity_id in (${slugsIn(srcRows)});

do $op$ begin
  if exists (select 1 from public.dle_entities where game_id = 'otakudle-one-piece') then
    perform public.dle_refresh_entities('otakudle-one-piece');
  end if;
end $op$;
`;
// One DO block each (owner, 2026-11-09): the owner may apply them from the Supabase SQL Editor.
writeFileSync(path.join(LAUNCH, 'L17-l1-op-affiliation.sql'), toSingleDoBlock(sql, 'o1l17'));
writeFileSync(path.join(LAUNCH, 'L17-l1-op-affiliation.rollback.sql'), toSingleDoBlock(rb, 'o1l17r'));
console.log(stats);
